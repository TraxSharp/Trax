// The C# emitter: one machine's typed view for a .NET client, from the same model the TypeScript twin is written from.
// It declares the states and triggers as enums, a record per context and per input, the IR the view was generated
// from with its hash, and a typed client over Trax.StateMachine.Client's ServerMachineController that predicts with
// the machine built from that IR.

import { escapeBidi, machineModel, type FieldModel, type MachineModel, type TypeRef, type ValueRef } from "./model";
import type { IrDocument } from "../rules/irMachine";

/** How {@link generateCSharpView} writes a view. */
export interface CSharpViewOptions {
  /** The namespace the view is declared in. Defaults to `Trax.Machines`. */
  namespace?: string;
  /**
   * The IR exactly as the host exported it (the committed `ir.json`, trailing newline stripped). The view embeds it, and
   * its SHA-256 is the hash the host's documents carry.
   */
  irText: string;
  /** The SHA-256 of `irText`. */
  irHash: string;
}

// Every type the view uses and does not declare, by its full name: the view's own types are named after the machine
// (`ir` declares `IrMachine`, `client-manifest` `ClientManifestMachine`), and one of them must never stand in for the
// runtime's. The view imports no namespace, so it compiles with or without implicit usings.
const SM = "global::Trax.StateMachine";
const SMC = "global::Trax.StateMachine.Client";
const STJ = "global::System.Text.Json";
const TASK = "global::System.Threading.Tasks.Task";

/**
 * Writes the C# view of one machine: `<Machine>.g.cs`. It needs `Trax.StateMachine.Client`, and nothing else beyond
 * the base class library. A machine whose names would write two C# members or types of one name, or a member C# does
 * not allow, is refused naming both, rather than written as a view that does not compile.
 */
export function generateCSharpView(ir: IrDocument, options: CSharpViewOptions): string {
  const model = machineModel(ir);
  const ns = options.namespace ?? "Trax.Machines";
  if (!/^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$/.test(ns))
    throw new Error(`The namespace ${JSON.stringify(ns)} is not a C# namespace.`);
  if (options.irText.includes('""""') || !options.irText.startsWith("{") || !options.irText.endsWith("}"))
    throw new Error("The IR text is not a JSON object the view can embed.");

  const m = model.pascal;
  const refuse = `Rename one of them in the machine '${ir.id}'.`;
  for (const [what, names] of [["state", model.states], ["trigger", model.triggers]] as const)
    for (const name of names)
      if (name.includes("$") || UNSUPPORTED.has(name))
        throw new Error(
          `The machine '${ir.id}' has the ${what} ${JSON.stringify(name)}, which C# does not take as a member name.`,
        );
  const types = new Names(refuse);
  const out: string[] = [
    "// <auto-generated>",
    `// AUTO-GENERATED from ${ir.id}.ir.json by generateCSharpView. Do not edit by hand.`,
    "// </auto-generated>",
    "#nullable enable",
    "",
    `namespace ${ns};`,
    "",
    `/// <summary>The states of the ${ir.id} machine.</summary>`,
    `public enum ${types.claim(`${m}State`, "the states' enum")}`,
    "{",
    ...enumMembers(model.states, "state", refuse),
    "}",
    "",
    `/// <summary>The triggers a client of the ${ir.id} machine sends.</summary>`,
    `public enum ${types.claim(`${m}Trigger`, "the triggers' enum")}`,
    "{",
    ...enumMembers(model.triggers, "trigger", refuse),
    "}",
    "",
  ];

  const records: { name: string; fields: readonly FieldModel[]; about: string; owner: string }[] = [];
  for (const { state, record } of model.contexts)
    records.push({ name: `${m}${record.suffix}`, fields: record.fields, about: `The context of ${state}.`, owner: `the context of ${state}` });
  for (const { trigger, record } of model.inputs)
    if (record)
      records.push({ name: `${m}${record.suffix}`, fields: record.fields, about: `The input of ${trigger}.`, owner: `the input of ${trigger}` });
  for (const record of records)
    out.push(...emitRecord(types.claim(record.name, record.owner), record.fields, record.about, types, refuse), "");

  types.claim(`${m}Machine`, "the machine's class");
  types.claim(`${m}Client`, "the client's class");
  out.push(...emitMachine(model, ir, options), "", ...emitClient(model, refuse), "");
  return out.join("\n");
}

// The names one C# scope declares: a second claim of a name is refused naming both owners.
class Names {
  private readonly owners = new Map<string, string>();

  constructor(private readonly rename: string) {}

  claim(name: string, owner: string): string {
    const other = this.owners.get(name);
    if (other !== undefined) throw new Error(`${other} and ${owner} both write the C# name '${name}'. ${this.rename}`);
    this.owners.set(name, owner);
    return name;
  }
}

function enumMembers(names: readonly string[], what: string, refuse: string): string[] {
  const members = new Names(refuse);
  return names.map((name) => `    ${members.claim(identifier(name), `the ${what} ${name}`)},`);
}

// The members a record declares or inherits whatever its fields are: a property of one of these names would clash
// with it or hide it.
const RECORD_MEMBERS = new Set([
  "Clone",
  "Deconstruct",
  "EqualityContract",
  "Equals",
  "Finalize",
  "GetHashCode",
  "GetType",
  "MemberwiseClone",
  "PrintMembers",
  "ReferenceEquals",
  "ToString",
]);

// A record, then every record its fields hold, each named after the property it is in.
function emitRecord(
  name: string,
  fields: readonly FieldModel[],
  about: string,
  types: Names,
  refuse: string,
): string[] {
  const nested: string[][] = [];
  const lines = [`/// <summary>${about}</summary>`, `public sealed record ${name}`, "{"];
  const members = new Names(refuse);
  members.claim(name, `the record ${name}`);
  // The view reads and writes JSON with the web defaults, which match a property's name ignoring case: two fields of
  // one record that differ only in case would be the same property to the serializer.
  const folded = new Map<string, string>();
  for (const field of fields) {
    const other = folded.get(field.name.toLowerCase());
    if (other !== undefined)
      throw new Error(
        `The fields ${JSON.stringify(other)} and ${JSON.stringify(field.name)} of ${name} differ only in case, which the view's JSON reads as one field. ${refuse}`,
      );
    folded.set(field.name.toLowerCase(), field.name);
  }
  fields.forEach((field, i) => {
    let property = memberName(field.name);
    if (property === name) property += "Value";
    if (RECORD_MEMBERS.has(property))
      throw new Error(
        `The field ${JSON.stringify(field.name)} of ${name} would write the property ${property}, which every C# record has. Rename it in the machine.`,
      );
    const owner = `the field ${JSON.stringify(field.name)} of ${name}`;
    members.claim(property, owner);
    const type = csType(field.type, `${name}${property}`, nested, { types, refuse, owner });
    if (i > 0) lines.push("");
    lines.push(`    [global::System.Text.Json.Serialization.JsonPropertyName(${csString(field.name)})]`);
    lines.push(
      field.nullable
        ? `    public ${type}? ${property} { get; init; }`
        : `    public required ${type} ${property} { get; init; }`,
    );
  });
  lines.push("}");
  return [...lines, ...nested.flatMap((n) => ["", ...n])];
}

// The type names a record's nested records claim, what to say on a clash, and the field they are written for.
interface Scope {
  types: Names;
  refuse: string;
  owner: string;
}

function csType(type: TypeRef, name: string, nested: string[][], scope: Scope): string {
  switch (type.kind) {
    case "string":
    case "literals":
      return "string";
    case "number":
      return "double";
    case "integer":
      return "long";
    case "boolean":
      return "bool";
    case "unknownList":
      return `${STJ}.Nodes.JsonArray`;
    case "unknownObject":
      return `${STJ}.Nodes.JsonObject`;
    case "record":
      scope.types.claim(name, scope.owner);
      nested.push(emitRecord(name, type.fields, `A value of ${name}.`, scope.types, scope.refuse));
      return name;
    case "list":
      return `global::System.Collections.Generic.IReadOnlyList<${valueType(type.of, `${name}Item`, nested, scope)}>`;
    case "map":
      return `global::System.Collections.Generic.IReadOnlyDictionary<string, ${valueType(type.of, `${name}Value`, nested, scope)}>`;
  }
}

const valueType = (value: ValueRef, name: string, nested: string[][], scope: Scope): string =>
  `${csType(value.type, name, nested, scope)}${value.nullable ? "?" : ""}`;

function emitMachine(model: MachineModel, ir: IrDocument, options: CSharpViewOptions): string[] {
  const m = model.pascal;
  return [
    `/// <summary>The ${ir.id} machine as this view was generated for it.</summary>`,
    `public static class ${m}Machine`,
    "{",
    "    /// <summary>The machine's id.</summary>",
    `    public const string Id = ${csString(ir.id)};`,
    "",
    "    /// <summary>The SHA-256 of <see cref=\"Ir\"/>: the hash the host's documents for this version carry.</summary>",
    `    public const string IrHash = ${csString(options.irHash)};`,
    "",
    "    /// <summary>The IR, as the host exported it.</summary>",
    // A raw literal keeps the IR readable; one holding a character C# reads as a line break, which a single-line raw
    // literal cannot, or a bidirectional control, which a raw literal would show as it is, is written as an escaped
    // one, which holds the same text.
    `    public const string Ir = ${/[\r\n\u0085\u2028\u2029]/.test(options.irText) || escapeBidi(options.irText) !== options.irText ? csString(options.irText) : `""""${options.irText}""""`};`,
    "",
    "    /// <summary>The engine built from <see cref=\"Ir\"/>.</summary>",
    `    public static ${SM}.IrMachine Create() => new(${STJ}.Nodes.JsonNode.Parse(Ir)!.AsObject());`,
    "}",
  ];
}

function emitClient(model: MachineModel, refuse: string): string[] {
  const m = model.pascal;
  // The members the client always declares, and its own name, which no member may take.
  const members = new Names(refuse);
  for (const fixed of [`${m}Client`, "Json", "Create", "Controller", "View", "State", "Changed", "StartAsync", "RetryAsync", "AvailableTriggers", "Dispose", "ContextIn"])
    members.claim(fixed, `the client's own ${fixed}`);
  const lines = [
    `/// <summary>`,
    `/// Drives one instance of the ${model.id} machine a host serves: <see cref="${SMC}.ServerMachineController"/> with its states,`,
    `/// triggers, contexts and inputs typed, predicting with the machine built from the IR.`,
    `/// </summary>`,
    `public sealed class ${m}Client : global::System.IDisposable`,
    "{",
    `    private static readonly ${STJ}.JsonSerializerOptions Json = new(${STJ}.JsonSerializerDefaults.Web)`,
    "    {",
    `        DefaultIgnoreCondition = ${STJ}.Serialization.JsonIgnoreCondition.WhenWritingNull,`,
    "    };",
    "",
    `    /// <summary>Wraps a controller already built for the ${model.id} machine.</summary>`,
    `    public ${m}Client(${SMC}.ServerMachineController controller) => Controller = controller;`,
    "",
    "    /// <summary>",
    `    /// Builds the client for <paramref name="machine"/>, the ${model.id} machine as the host's manifest lists it, which must`,
    "    /// be the version this view was generated for.",
    "    /// </summary>",
    "    /// <exception cref=\"global::System.ArgumentException\">The manifest's machine is another machine, or another version of it.</exception>",
    `    public static ${m}Client Create(`,
    `        ${SM}.ClientManifestMachine machine,`,
    `        ${SMC}.IMachineServer server,`,
    "        string? id = null,",
    "        global::System.Func<string>? newRequestId = null",
    "    )",
    "    {",
    "        global::System.ArgumentNullException.ThrowIfNull(machine);",
    `        if (machine.Id != ${m}Machine.Id || machine.IrHash != ${m}Machine.IrHash)`,
    "            throw new global::System.ArgumentException(",
    `                $"The manifest's machine '{machine.Id}' (IR {machine.IrHash}) is not the version this view was generated for (IR {${m}Machine.IrHash}). Generate the view again from the host's manifest.",`,
    "                nameof(machine)",
    "            );",
    `        return new ${m}Client(`,
    `            new ${SMC}.ServerMachineController(`,
    `                new ${SMC}.ServerMachineOptions`,
    "                {",
    "                    Machine = machine,",
    "                    Server = server,",
    `                    Predictor = ${SMC}.MachinePredictor.FromIr(machine),`,
    "                    Id = id,",
    "                    NewRequestId = newRequestId,",
    "                }",
    "            )",
    "        );",
    "    }",
    "",
    "    /// <summary>The untyped controller underneath.</summary>",
    `    public ${SMC}.ServerMachineController Controller { get; }`,
    "",
    "    /// <summary>What the controller shows now.</summary>",
    `    public ${SMC}.MachineView View => Controller.View;`,
    "",
    "    /// <summary>The state shown, or null before the first snapshot.</summary>",
    `    public ${m}State? State => View.Snapshot is { } shown ? global::System.Enum.Parse<${m}State>(shown.State) : null;`,
    "",
    "    /// <summary>Raised after every change of <see cref=\"View\"/>.</summary>",
    "    public event global::System.EventHandler? Changed",
    "    {",
    "        add => Controller.Changed += value;",
    "        remove => Controller.Changed -= value;",
    "    }",
    "",
    "    /// <summary>Opens the instance, or starts one.</summary>",
    `    public ${TASK} StartAsync() => Controller.StartAsync();`,
    "",
    "    /// <summary>Resends what last failed, under the same request id.</summary>",
    `    public ${TASK}<${SMC}.SendOutcome> RetryAsync() => Controller.RetryAsync();`,
    "",
    "    /// <summary>The triggers with an edge out of the shown state.</summary>",
    `    public global::System.Collections.Generic.IReadOnlyList<${m}Trigger> AvailableTriggers() =>`,
    "        global::System.Linq.Enumerable.ToList(",
    `            global::System.Linq.Enumerable.Select(Controller.AvailableTriggers(), global::System.Enum.Parse<${m}Trigger>)`,
    "        );",
  ];

  for (const { state } of model.contexts) {
    const property = members.claim(`${memberName(state)}Context`, `the context of ${state}`);
    lines.push(
      "",
      `    /// <summary>The context shown, while the instance is in ${state}; null in any other state.</summary>`,
      `    public ${m}${state}Context? ${property} => ContextIn<${m}${state}Context>(${m}State.${identifier(state)});`,
    );
  }

  for (const { trigger, record } of model.inputs) {
    const name = memberName(trigger);
    const send = members.claim(`Send${name}Async`, `the trigger ${trigger}`);
    const can = members.claim(`CanSend${name}`, `the trigger ${trigger}`);
    const parameter = record ? `${m}${record.suffix} input` : "";
    const node = record ? `, ${STJ}.JsonSerializer.SerializeToNode(input, Json)` : "";
    lines.push(
      "",
      `    /// <summary>Sends ${trigger}.</summary>`,
      `    public ${TASK}<${SMC}.SendOutcome> ${send}(${parameter}) => Controller.SendAsync(${csString(trigger)}${node});`,
      "",
      `    /// <summary>Whether ${trigger} would fire from what is shown.</summary>`,
      `    public bool ${can}(${parameter}) => Controller.CanSend(${csString(trigger)}${node});`,
    );
  }

  lines.push(
    "",
    "    /// <summary>Closes the stream and drops every late answer.</summary>",
    "    public void Dispose() => Controller.Dispose();",
    "",
    `    private T? ContextIn<T>(${m}State state)`,
    "        where T : class =>",
    `        State == state ? ${STJ}.JsonSerializer.Deserialize<T>(View.Snapshot!.Context, Json) : null;`,
    "}",
  );
  return lines;
}

const KEYWORDS = new Set(
  (
    "abstract as base bool break byte case catch char checked class const continue decimal default delegate do double " +
    "else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal " +
    "is lock long namespace new null object operator out override params private protected public readonly ref return " +
    "sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked " +
    "unsafe ushort using virtual void volatile while"
  ).split(" "),
);

// C#'s undocumented keywords: not even an @ makes one a name.
const UNSUPPORTED = new Set(["__arglist", "__makeref", "__reftype", "__refvalue"]);

// A name the IR already holds as an identifier (a state, a trigger), escaped when it is a C# keyword.
const identifier = (name: string): string => (KEYWORDS.has(name) ? `@${name}` : name);

// A JSON field name as a C# member: PascalCase over its letters and digits, never starting with a digit.
function memberName(name: string): string {
  const words = name.split(/[^A-Za-z0-9]+/).filter((w) => w.length > 0);
  const joined = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");
  if (joined.length === 0) return "Value";
  return /^[0-9]/.test(joined) ? `_${joined}` : joined;
}

// A C# string literal: JSON's escapes are C#'s for every character JSON escapes. JSON leaves U+0085, U+2028 and
// U+2029 as they are, and C# reads each as a line break, which a regular string literal cannot hold, so they are
// escaped too, as are the bidirectional controls, which would reorder how the file reads.
const csString = (value: string): string =>
  escapeBidi(
    JSON.stringify(value).replace(
      /[\u0085\u2028\u2029]/g,
      (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`,
    ),
  );

