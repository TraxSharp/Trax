using System.Text;
using System.Text.Json;
using GraphQLParser;
using GraphQLParser.AST;

namespace Trax.Cli.Clients;

/// <summary>
/// What <c>trax client --operations</c> generates from: the operations schema's SDL and the documents the console
/// sends.
/// </summary>
/// <param name="Schema">The operations schema, as SDL (Trax.Api.Dashboard's <c>operations.graphql</c>).</param>
/// <param name="Documents">The <c>.graphql</c> files the console wrote.</param>
internal sealed record OperationsGenerateOptions(
    string Schema,
    IReadOnlyList<ClientDocumentFile> Documents
);

internal sealed partial class ClientGenerator
{
    /// <summary>The file Trax.Api.Dashboard embeds and a host registers the console's documents from.</summary>
    public const string ConsoleDocumentsFileName = "console-documents.json";

    private const string OperationsHeader =
        "// Generated by trax client from the operations schema. Do not edit.\n";

    private static readonly string OperationsHeaderLine = OperationsHeader.TrimEnd('\n');

    // The names the operations client's runtime exports from the index, which no document or type may take.
    private static readonly string[] OperationsRuntimeNames =
    [
        "configureTraxOperations",
        "traxTransport",
        "httpTransport",
        "requireSecureEndpoint",
        "requireSecureSocket",
        "execute",
        "send",
        "subscribe",
        "TraxOperationError",
        "TraxTransportError",
        "TraxDocument",
        "TraxRequest",
        "TraxAnswer",
        "TraxGraphQLError",
        "TraxSink",
        "TraxTransport",
        "HttpTransport",
        "HttpTransportOptions",
        "ResultOf",
        "VariablesOf",
    ];

    /// <summary>
    /// Every file of an operations client, in path order: the runtime, the enums and inputs the schema declares, a
    /// module per document (its id, its text, its variables and result types, and the function that sends it), the
    /// index, and <c>console-documents.json</c>, which holds every document a host registers.
    /// </summary>
    public static IReadOnlyList<ClientFile> Render(OperationsGenerateOptions options)
    {
        GraphQLDocument sdl;
        try
        {
            sdl = Parser.Parse(options.Schema);
        }
        catch (GraphQLParser.Exceptions.GraphQLParserException ex)
        {
            throw new InvalidOperationException(
                $"The operations schema is not GraphQL SDL ({ex.Message.Trim()}).",
                ex
            );
        }
        var types = new SdlTypes(sdl);
        var roots = OperationsRoots.Of(sdl);
        var documents = ClientDocumentSet.ReadOperations(options.Documents, types, roots);

        var names = new Names();
        foreach (var name in OperationsRuntimeNames)
            names.Claim(name, "the client's runtime");
        foreach (var type in types.Declared)
            names.Claim(type, $"the GraphQL type {type}");
        var paths = new Names(StringComparer.OrdinalIgnoreCase);

        var files = new List<ClientFile>
        {
            new("client.g.ts", OperationsClient),
            new("types.g.ts", types.Render(OperationsHeader)),
        };
        var index = new StringBuilder(OperationsHeader);
        index.Append(
            "export { configureTraxOperations, traxTransport, httpTransport, requireSecureEndpoint, requireSecureSocket, "
                + "execute, send, subscribe, TraxOperationError, "
                + "TraxTransportError, type TraxDocument, type TraxRequest, type TraxAnswer, type TraxGraphQLError, "
                + "type TraxSink, type TraxTransport, type HttpTransport, type HttpTransportOptions, type ResultOf, "
                + "type VariablesOf } from \"./client.g\";\n"
        );
        index.Append("export type * from \"./types.g\";\n");

        foreach (var operation in documents.Operations)
        {
            var owner = $"the console document {operation.Name} ({operation.Source})";
            var function = names.Claim(
                TypeScript.Identifier(Lower(operation.Name), "operation"),
                owner
            );
            var upper = TypeScript.Upper(function);
            var document = names.Claim($"{function}Document", owner);
            var variables = names.Claim($"{upper}Variables", owner);
            var result = names.Claim($"{upper}Result", owner);
            paths.Claim($"documents/{function}.g.ts", owner);
            files.Add(
                new(
                    $"documents/{function}.g.ts",
                    OperationModule(
                        operation,
                        function,
                        document,
                        variables,
                        result,
                        types,
                        roots,
                        documents
                    )
                )
            );
            index.Append(
                $"export {{ {function}, {document}, type {variables}, type {result} }} from \"./documents/{function}.g\";\n"
            );
        }

        files.Add(new("index.g.ts", index.ToString()));
        files.Add(new(ConsoleDocumentsFileName, ConsoleDocumentsJson(documents)));
        return files.OrderBy(f => f.Path, StringComparer.Ordinal).ToList();
    }

    /// <summary>Writes the operations client under <paramref name="outDir"/>, as <see cref="Write(ClientGenerateOptions, string)"/> does.</summary>
    public static IReadOnlyList<ClientFile> Write(
        OperationsGenerateOptions options,
        string outDir
    ) => Write(Render(options), outDir, Writer.OperationsTypeScript);

    /// <summary>What differs between the operations client the documents generate and the one under <paramref name="outDir"/>.</summary>
    public static IReadOnlyList<ClientDrift> Check(
        OperationsGenerateOptions options,
        string outDir
    ) => Check(Render(options), outDir, Writer.OperationsTypeScript);

    // A console document's module: its descriptor, the types of its variables and of what it selects, and the function
    // that sends it (or, for a subscription, follows it).
    private static string OperationModule(
        ClientOperation operation,
        string function,
        string document,
        string variablesType,
        string resultType,
        SdlTypes types,
        OperationsRoots roots,
        ClientDocumentSet documents
    )
    {
        var owner = $"The console document {operation.Name} ({operation.Source})";
        var selections = new SelectionTypes(
            types,
            documents.Fragments.ToDictionary(
                f => f.Key,
                f => f.Value.Definition,
                StringComparer.Ordinal
            )
        );
        var kind = operation.Operation.Operation switch
        {
            OperationType.Mutation => "mutation",
            OperationType.Subscription => "subscription",
            _ => "query",
        };
        var root = kind switch
        {
            "mutation" => roots.Mutation,
            "subscription" => roots.Subscription,
            _ => roots.Query,
        };
        var used = new HashSet<string>(StringComparer.Ordinal);
        var answer = selections.Of(
            new GraphQLNonNullType(new GraphQLNamedType(new GraphQLName(root))),
            operation.Operation.SelectionSet,
            owner,
            used
        );

        var variables = operation.Operation.Variables?.Items ?? [];
        var variableLines = new StringBuilder();
        foreach (var variable in variables)
        {
            var name = variable.Variable.Name.StringValue;
            var optional =
                variable.Type is not GraphQLNonNullType || variable.DefaultValue is not null;
            variableLines.Append(
                $"  {SdlTypes.Property(name)}{(optional ? "?" : "")}: {types.InputType(variable.Type)};\n"
            );
        }
        var imports = types
            .NamesIn(variables.Select(v => v.Type))
            .Concat(used)
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToList();
        var required = variables.Any(v => v.Type is GraphQLNonNullType && v.DefaultValue is null);

        var sb = new StringBuilder(OperationsHeader);
        sb.Append(
            kind == "subscription"
                ? "import { subscribe, type TraxDocument, type TraxSink } from \"../client.g\";\n"
                : "import { send, type TraxDocument } from \"../client.g\";\n"
        );
        if (imports.Count > 0)
            sb.Append($"import type {{ {string.Join(", ", imports)} }} from \"../types.g\";\n");
        sb.Append('\n');
        sb.Append($"/** The variables '{EscapeDocText(operation.Name)}' takes. */\n");
        sb.Append(
            variables.Count == 0
                ? $"export type {variablesType} = Record<string, never>;\n\n"
                : $"export interface {variablesType} {{\n{variableLines}}}\n\n"
        );
        sb.Append(
            $"/** What '{EscapeDocText(operation.Name)}' answers: the fields it selects. */\n"
        );
        sb.Append($"export type {resultType} = {answer};\n\n");
        sb.Append(
            operation.Id.Length == 0
                ? $"/** The {kind} '{EscapeDocText(operation.Name)}' ({EscapeDocText(operation.Source)}). A host runs it as text, behind its own gate, and never registers it. */\n"
                : $"/** The {kind} '{EscapeDocText(operation.Name)}' ({EscapeDocText(operation.Source)}), and the id a host that serves the console registers it under. */\n"
        );
        sb.Append(
            $"export const {document}: TraxDocument<{variablesType}, {resultType}> = {{\n"
                + $"  name: {TypeScript.Literal(operation.Name)},\n"
                + $"  kind: {TypeScript.Literal(kind)},\n"
                + $"  id: {(operation.Id.Length == 0 ? "null" : TypeScript.Literal(operation.Id))},\n"
                + $"  text: {TypeScript.Literal(operation.Text)},\n"
                + "};\n\n"
        );
        var parameter =
            variables.Count == 0 ? ""
            : required ? $"variables: {variablesType}"
            : $"variables: {variablesType} = {{}}";
        var value = variables.Count == 0 ? "{}" : "variables";
        if (kind == "subscription")
        {
            sb.Append(
                "/** Follows the stream until the function it returns is called. Each frame goes to `sink.next`. */\n"
            );
            sb.Append(
                $"export function {function}({(parameter.Length == 0 ? "" : parameter + ", ")}sink: TraxSink<{resultType}>): () => void {{\n"
            );
            sb.Append($"  return subscribe({document}, {value}, sink);\n");
        }
        else
        {
            sb.Append(
                "/** Sends the document and returns what it answers; throws a TraxOperationError when the host refuses it. */\n"
            );
            sb.Append($"export function {function}({parameter}): Promise<{resultType}> {{\n");
            sb.Append($"  return send({document}, {value});\n");
        }
        sb.Append("}\n");
        return sb.ToString();
    }

    // The documents a host that serves the console registers: each one with an id, by name, as Trax.Api.Dashboard
    // embeds them.
    private static string ConsoleDocumentsJson(ClientDocumentSet documents) =>
        JsonSerializer
            .Serialize(
                new
                {
                    format = 1,
                    documents = documents
                        .Operations.Where(o => o.Id.Length > 0)
                        .Select(o => new { name = o.Name, text = o.Text }),
                },
                new JsonSerializerOptions
                {
                    WriteIndented = true,
                    Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
                }
            )
            .Replace("\r\n", "\n") + "\n";

    private const string OperationsClient =
        OperationsHeader
        + """
            import { createClient, type Client, type ClientOptions } from "graphql-ws";

            /** One document the client sends: its operation's name and kind, the id a host registers it under, and its text. */
            export interface TraxDocument<TVariables, TResult> {
              readonly name: string;
              readonly kind: "query" | "mutation" | "subscription";
              /** The persisted id, or null for a document a host runs as text and never registers. */
              readonly id: string | null;
              readonly text: string;
              /** Never set: carries the variables' type, so a hook infers it from the document. */
              readonly variables?: TVariables;
              /** Never set: carries the result's type, so a hook infers it from the document. */
              readonly result?: TResult;
            }

            /** The variables a document takes. */
            export type VariablesOf<D> = D extends TraxDocument<infer V, unknown> ? V : never;

            /** What a document answers. */
            export type ResultOf<D> = D extends TraxDocument<unknown, infer R> ? R : never;

            /** A document and the variables it is sent with. */
            export interface TraxRequest {
              readonly document: TraxDocument<unknown, unknown>;
              readonly variables: Readonly<Record<string, unknown>>;
            }

            /** One error of a GraphQL answer. */
            export interface TraxGraphQLError {
              readonly message: string;
              readonly path?: readonly (string | number)[];
              readonly extensions?: Readonly<Record<string, unknown>> & { readonly code?: string };
            }

            /** A GraphQL answer as the host sends it: the data, the errors, or both. */
            export interface TraxAnswer {
              readonly data?: unknown;
              readonly errors?: readonly TraxGraphQLError[];
            }

            /** Where a stream's frames go. */
            export interface TraxSink<T> {
              next(value: T): void;
              error(error: unknown): void;
              complete(): void;
            }

            /**
             * How a request reaches a host. The client never talks to the network itself: an app gives it httpTransport,
             * or its own (a mock, a recording, a wrapper that counts what is in flight).
             */
            export interface TraxTransport {
              /** Sends a query or mutation. Throws only when no answer arrived; a refusal is an answer with errors. */
              execute(request: TraxRequest): Promise<TraxAnswer>;
              /** Follows a subscription, each frame an answer, until the function it returns is called. */
              subscribe(request: TraxRequest, sink: TraxSink<TraxAnswer>): () => void;
            }

            let transport: TraxTransport | null = null;

            /** Tells the client how to reach the host. Call it before anything is sent, and again to replace it. */
            export function configureTraxOperations(next: TraxTransport): void {
              transport = next;
            }

            /** The transport configureTraxOperations was given, or a refusal naming what to call. */
            export function traxTransport(): TraxTransport {
              if (!transport) throw new Error("Call configureTraxOperations(transport) before using the operations client.");
              return transport;
            }

            /** A document the host answered with errors: `code` is the first one's `extensions.code`, `errors` all of them. */
            export class TraxOperationError extends Error {
              readonly code: string | undefined;
              readonly errors: readonly TraxGraphQLError[];

              constructor(errors: readonly TraxGraphQLError[]) {
                super(errors.map((e) => e.message).join("\n"));
                this.name = "TraxOperationError";
                this.code = errors[0]?.extensions?.code;
                this.errors = errors;
              }
            }

            /** A request that got no GraphQL answer: the host was unreachable, or answered with something else. */
            export class TraxTransportError extends Error {
              readonly status: number | undefined;

              constructor(message: string, status?: number, options?: { cause?: unknown }) {
                super(message, options);
                this.name = "TraxTransportError";
                this.status = status;
              }
            }

            /** Sends a query or mutation and returns the whole answer, errors included, for a caller that shows both. */
            export function execute<V, R>(
              document: TraxDocument<V, R>,
              variables: V,
            ): Promise<{ data?: R | null; errors?: readonly TraxGraphQLError[] }> {
              return traxTransport().execute({ document, variables: withoutUndefined(variables) }) as Promise<{
                data?: R | null;
                errors?: readonly TraxGraphQLError[];
              }>;
            }

            /** Sends a query or mutation and returns its data; throws a TraxOperationError when the answer holds errors. */
            export async function send<V, R>(document: TraxDocument<V, R>, variables: V): Promise<R> {
              const answer = await execute(document, variables);
              if (answer.errors?.length) throw new TraxOperationError(answer.errors);
              return answer.data as R;
            }

            /** Follows a subscription. A frame with errors ends it through `sink.error`. */
            export function subscribe<V, R>(document: TraxDocument<V, R>, variables: V, sink: TraxSink<R>): () => void {
              let stop: (() => void) | null = null;
              let stopped = false;
              stop = traxTransport().subscribe(
                { document, variables: withoutUndefined(variables) },
                {
                  next(answer) {
                    if (stopped) return;
                    if (answer.errors?.length) {
                      stopped = true;
                      stop?.();
                      sink.error(new TraxOperationError(answer.errors));
                      return;
                    }
                    sink.next(answer.data as R);
                  },
                  error(error) {
                    if (stopped) return;
                    stopped = true;
                    sink.error(error);
                  },
                  complete() {
                    if (stopped) return;
                    stopped = true;
                    sink.complete();
                  },
                },
              );
              if (stopped) stop();
              return () => {
                stopped = true;
                stop?.();
              };
            }

            /** What httpTransport needs. Nothing here is generated: the app gives it at run time. */
            export interface HttpTransportOptions {
              /** The GraphQL endpoint (`https://ops.example.com/trax/graphql`). */
              url: string;
              /** The GraphQL socket (`wss://ops.example.com/trax/graphql`), for the streams. */
              socketUrl: string;
              /** The headers each request carries, read per request so a rotating credential stays fresh. */
              headers?: () => Record<string, string>;
              /** What the socket sends in `connection_init`: a browser cannot set headers on a socket. */
              connectionParams?: ClientOptions["connectionParams"];
              /**
               * Whether a document goes by its id rather than its text. By default every document that has an id does; a
               * host that registered only some of them (or none, when it runs no persisted operations) names which.
               */
              byId?: (document: TraxDocument<unknown, unknown>) => boolean;
              /** The rest of the socket's options (retries, `on` listeners), passed to graphql-ws as they are. */
              socket?: Omit<ClientOptions, "url" | "connectionParams" | "jsonMessageReplacer">;
              /** The fetch to send with, looked up per request when not given. */
              fetch?: typeof fetch;
              /**
               * Lets the transport send to an absolute `http:` url, or open a `ws:` socketUrl, on a host that is not
               * loopback. Only for a trusted network: the headers and connectionParams would travel in cleartext. Off by
               * default, and httpTransport refuses such a url.
               */
              allowInsecureTransport?: boolean;
              /** The most bytes of an answer the transport reads before it refuses it. 16 MiB when not given. */
              maxResponseBytes?: number;
            }

            /** httpTransport's transport, and a way to drop its socket so the next stream opens a new one. */
            export interface HttpTransport extends TraxTransport {
              /** Closes the socket at once; graphql-ws reconnects the streams that are still followed. */
              terminate(): void;
              /** Closes the socket and stops every stream. */
              dispose(): void;
            }

            /**
             * A transport over HTTP POST and one graphql-ws socket. A document goes by its id when `byId` says so: over HTTP
             * the body carries the id and no text, and over the socket the text is left out of the subscribe message. It
             * refuses a url or socketUrl that would travel in cleartext to another host (see requireSecureEndpoint and
             * requireSecureSocket) unless `allowInsecureTransport` is set, follows no redirect, and reads at most
             * `maxResponseBytes` of an answer.
             */
            export function httpTransport(options: HttpTransportOptions): HttpTransport {
              requireSecureEndpoint(options.url, options.allowInsecureTransport);
              requireSecureSocket(options.socketUrl, options.allowInsecureTransport);
              let socket: Client | null = null;
              const byId = options.byId ?? ((document) => document.id !== null);
              const open = (): Client =>
                (socket ??= createClient({
                  lazy: true,
                  retryAttempts: Number.POSITIVE_INFINITY,
                  ...options.socket,
                  url: options.socketUrl,
                  connectionParams: options.connectionParams,
                  jsonMessageReplacer: (key, value) =>
                    key === "payload" && isRecord(value) && value.id && value.query === "" ? withoutQuery(value) : value,
                }));
              const payload = (request: TraxRequest) =>
                byId(request.document) && request.document.id !== null
                  ? { id: request.document.id, query: "", operationName: request.document.name, variables: request.variables }
                  : { query: request.document.text, operationName: request.document.name, variables: request.variables };
              return {
                async execute(request) {
                  const body = payload(request);
                  const send = options.fetch ?? fetch;
                  let response: Response;
                  try {
                    response = await send(options.url, {
                      method: "POST",
                      headers: { "Content-Type": "application/json", Accept: "application/graphql-response+json, application/json", ...options.headers?.() },
                      body: JSON.stringify(body.query === "" ? withoutQuery(body) : body),
                      // A redirect would carry the headers to wherever it points.
                      redirect: "error",
                    });
                  } catch (cause) {
                    throw new TraxTransportError(`The host could not be reached: ${String(cause)}`, undefined, { cause });
                  }
                  let answer: unknown;
                  try {
                    answer = await readJson(response, options.maxResponseBytes);
                  } catch (cause) {
                    if (cause instanceof RangeError) throw new TraxTransportError(cause.message, response.status, { cause });
                    throw new TraxTransportError(`The host answered ${response.status} with no GraphQL answer.`, response.status, {
                      cause,
                    });
                  }
                  if (!isRecord(answer) || (!("data" in answer) && !("errors" in answer)))
                    throw new TraxTransportError(`The host answered ${response.status} with no GraphQL answer.`, response.status);
                  return answer as TraxAnswer;
                },
                subscribe(request, sink) {
                  return open().subscribe(payload(request), {
                    next: (frame) => sink.next(frame as TraxAnswer),
                    error: (error) => sink.error(error),
                    complete: () => sink.complete(),
                  });
                },
                terminate() {
                  socket?.terminate();
                },
                dispose() {
                  const closing = socket;
                  socket = null;
                  void closing?.dispose();
                },
              };
            }

            function isRecord(value: unknown): value is Record<string, unknown> {
              return typeof value === "object" && value !== null;
            }

            function withoutQuery(value: Record<string, unknown>): Record<string, unknown> {
              return Object.fromEntries(Object.entries(value).filter(([key]) => key !== "query"));
            }

            function withoutUndefined(values: unknown): Readonly<Record<string, unknown>> {
              if (!isRecord(values)) return {};
              return Object.fromEntries(Object.entries(values).filter(([, value]) => value !== undefined));
            }

            """
        + OperationsEndpointGuard
        + TransportGuards;

    // The machine client's check of its url, which the operations client cannot import from the engine.
    private const string OperationsEndpointGuard = """

        /**
         * Refuses an absolute `http:` url whose host is not loopback (`localhost`, `127.0.0.0/8`, `::1`), since the
         * headers would travel in cleartext; a relative url is the page's own origin and is accepted. `allowInsecure`
         * lifts the refusal, for a network you trust.
         */
        export function requireSecureEndpoint(endpoint: string, allowInsecure: boolean | undefined): void {
          if (allowInsecure) return;
          let url: URL;
          try {
            url = new URL(endpoint);
          } catch {
            return;
          }
          if (url.protocol === "https:" || isLoopbackHost(url.hostname)) return;
          throw new Error(
            `The endpoint ${url.protocol}//${url.host} is not over TLS, so whatever authenticates the client would travel in cleartext. Use https://, a loopback host, or set allowInsecureTransport when the network is trusted.`,
          );
        }

        """;
}
