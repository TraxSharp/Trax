    // The query and the subscription of runProgress, or null when no train lets its starter follow it.
    private static (ClientManifestDocument Query, ClientManifestDocument Stream)? Progress(
        ClientManifest manifest
    )
    {
        if (manifest.Progress.Count == 0)
            return null;
        var query = manifest.Progress.SingleOrDefault(d => d.Operation == "query");
        var stream = manifest.Progress.SingleOrDefault(d => d.Operation == "subscription");
        if (query is null || stream is null || manifest.Progress.Count != 2)
            throw new InvalidOperationException(
                "The manifest's progress documents are not one query and one subscription. Export the manifest "
                    + "again from the host."
            );
        return (query, stream);
    }

    private static string ProgressModule(
        ClientManifestDocument query,
        ClientManifestDocument stream,
        ClientManifest manifest
    )
    {
        var followable = manifest
            .Trains.Where(t => t.Progress)
            .Select(t => t.Namespace is null ? t.Field : $"{t.Namespace}.{t.Field}")
            .Order(StringComparer.Ordinal)
            .ToList();
        var sb = new StringBuilder(Header);
        sb.Append("import \"./format.g\";\n");
        sb.Append("import { useEffect, useState, useSyncExternalStore } from \"react\";\n");
        sb.Append(
            "import { sendDocument, subscribeTrax, traxGeneration, traxSocket, TraxOperationError } from \"./client.g\";\n"
        );
        sb.Append("import type { RunProgress, RunProgressEvent } from \"./types.g\";\n\n");
        sb.Append("/** The persisted id of the runProgress query, which the host registered. */\n");
        sb.Append($"export const runProgressDocumentId = {TypeScript.Literal(query.Id)};\n\n");
        sb.Append(
            "/** The persisted id of the runProgress subscription, which the host registered. */\n"
        );
        sb.Append(
            $"export const runProgressEventsDocumentId = {TypeScript.Literal(stream.Id)};\n\n"
        );
        sb.Append(
            TypeScript.Doc(
                "Your run, read once: where it stands and the steps it took. Any run you did not start answers "
                    + "`problem.code` NOT_FOUND."
                    + (
                        followable.Count == 0
                            ? ""
                            : " Runs of these trains can be followed: "
                                + string.Join(", ", followable)
                                + "."
                    )
            )
        );
        sb.Append(
            """
            export function readRunProgress(runId: string): Promise<RunProgress> {
              return sendDocument(runProgressDocumentId, { runId }, ["runProgress"]);
            }

            /**
             * Follows your run: `onEvent` gets each change of state and each step as it happens, then `onEnd()` once the
             * stream ends, after the run does, or `onEnd(error)` when the host refused it. A `sequence` that skips a number
             * means events were lost: read the run again. Returns the function that stops following.
             */
            export function followRunProgress(
              runId: string,
              onEvent: (event: RunProgressEvent) => void,
              onEnd?: (error?: unknown) => void,
            ): () => void {
              const payload = { query: "", id: runProgressEventsDocumentId, variables: { runId } };
              return traxSocket().subscribe<{ runProgress: RunProgressEvent }>(payload, {
                next: (result) => {
                  const error = result.errors?.[0];
                  if (error) onEnd?.(new TraxOperationError(error.extensions?.code as string | undefined, error.message));
                  else if (result.data) onEvent(result.data.runProgress);
                },
                error: (error) => onEnd?.(error),
                complete: () => onEnd?.(),
              });
            }

            /** A run as useRunProgress shows it. */
            export interface RunProgressView {
              /** The run shown: the one asked for, or the retry that followed it. */
              runId: string | null;
              /** The runs before it, oldest first: each failed, and the scheduler retried it. */
              earlier: string[];
              state: RunProgress["state"];
              steps: RunProgress["steps"];
              failure: string | null;
              problem: RunProgress["problem"];
              /** The stream ended: the run ended with no retry to follow, or the host refused it. */
              ended: boolean;
            }

            const nothingYet: RunProgressView = { runId: null, earlier: [], state: null, steps: [], failure: null, problem: null, ended: false };

            /**
             * Your run, kept current: read once, then followed until it ends. A step replaces the one at its position, a lost
             * event reads the run again, and a failed run the scheduler retries is followed into its retry. After
             * configureTrax the run is read and followed again over the new connection. Pass null to follow nothing.
             */
            export function useRunProgress(runId: string | null | undefined): RunProgressView {
              const [view, setView] = useState<RunProgressView>(nothingYet);
              const [current, setCurrent] = useState<{ asked: string | null | undefined; run: string | null | undefined; earlier: string[] }>(
                { asked: runId, run: runId, earlier: [] },
              );
              if (current.asked !== runId) setCurrent({ asked: runId, run: runId, earlier: [] });
              const following = current.asked === runId ? current.run : runId;
              const earlier = current.asked === runId ? current.earlier : [];
              // configureTrax closes the socket the stream is on: the run is followed again over the new one.
              const generation = useSyncExternalStore(subscribeTrax, traxGeneration, traxGeneration);

              useEffect(() => {
                if (!following) return;
                let live = true;
                let last = 0;
                // How many events the stream delivered: a read sent before the last of them answers with an older run.
                let events = 0;
                // The view of this run: what was held, when it was this run's, else an empty one.
                const fresh = (v: RunProgressView): RunProgressView =>
                  v.runId === following ? v : { ...nothingYet, runId: following };
                // The read and the stream can both report the retry: the first moves on to it, the second finds it moved.
                const retry = (next: string) => {
                  if (live) setCurrent((c) => (c.run === following ? { ...c, run: next, earlier: [...c.earlier, following] } : c));
                };
                // A read answered after an event arrived never shows its state over the event's: only the steps it holds that
                // no event has reported are added. One that was sent for lost events is sent again, until it answers with no
                // event since.
                const read = (forLost: boolean) => {
                  const sent = events;
                  return readRunProgress(following).then(
                    (run) => {
                      if (!live) return;
                      if (run.retriedAs) return retry(run.retriedAs);
                      if (events !== sent) {
                        setView((prior) => {
                          const v = fresh(prior);
                          return { ...v, steps: v.steps.reduce(withStep, run.steps) };
                        });
                        if (forLost) void read(true);
                        return;
                      }
                      setView((v) => ({ ...fresh(v), state: run.state, steps: run.steps, failure: run.failure, problem: run.problem }));
                    },
                    () => undefined,
                  );
                };
                void read(false);
                const stop = followRunProgress(
                  following,
                  (event) => {
                    events += 1;
                    if (event.retriedAs) return retry(event.retriedAs);
                    if (last !== 0 && event.sequence !== last + 1) void read(true);
                    last = event.sequence;
                    setView((prior) => {
                      const v = fresh(prior);
                      return {
                      ...v,
                      state: event.state ?? v.state,
                      steps: event.step ? withStep(v.steps, event.step) : v.steps,
                      failure: event.failure ?? v.failure,
                      problem: event.problem ?? v.problem,
                      };
                    });
                  },
                  () => {
                    // The stream of an earlier connection ends when configureTrax closes its socket, not when the run does.
                    if (live && generation === traxGeneration()) setView((v) => ({ ...fresh(v), ended: true }));
                  },
                );
                return () => {
                  live = false;
                  stop();
                };
              }, [following, generation]);
              // A view of an earlier run is not shown: a run just asked for, or retried into, starts empty.
              return { ...(view.runId === (following ?? null) ? view : { ...nothingYet, runId: following ?? null }), earlier };
            }

            type Step = RunProgress["steps"][number];

            function withStep(steps: readonly Step[], step: Step): Step[] {
              const key = (s: Step) => `${s.position}:${s.kind}`;
              const at = steps.findIndex((s) => key(s) === key(step));
              return at < 0 ? [...steps, step] : steps.map((s, i) => (i === at ? step : s));
            }

            """
        );
        return sb.ToString();
    }

    private static string Requirement(ClientManifestRequirement? requires)
    {
        if (requires is null)
            return "";
        if (requires.Anonymous)
            return "Anyone may run it, signed in or not.";
        var parts = new List<string> { "Requires a signed-in caller" };
        foreach (var set in requires.RoleSets)
            parts.Add($"holding one of the roles {string.Join(", ", set)}");
        foreach (var policy in requires.Policies)
            parts.Add($"satisfying the policy {policy}");
        return string.Join(", ", parts) + ". The host checks it either way.";
    }

    private static string EscapeDocText(string text) => text.Replace("*/", "*\\/");

    // The identifiers the client's index exports, or the paths of its files, so two never collide.
    private sealed class Names(StringComparer? comparer = null)
    {
        private readonly Dictionary<string, string> _owners = new(
            comparer ?? StringComparer.Ordinal
        );

        public string Claim(string name, string owner)
        {
            if (_owners.TryGetValue(name, out var other))
                throw new InvalidOperationException(
                    other == owner
                        ? $"'{owner}' is listed twice in the manifest. Export the manifest again from the host."
                        : $"'{other}' and '{owner}' both generate the name '{name}'. Rename one of them on the host."
                );
            _owners[name] = owner;
            return name;
        }
    }
