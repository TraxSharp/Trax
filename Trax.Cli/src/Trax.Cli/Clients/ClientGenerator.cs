using System.Text;
using GraphQLParser;
using GraphQLParser.AST;
using Trax.Cli.Machines;
using Trax.Effect.StateMachine;

namespace Trax.Cli.Clients;

/// <summary>What <c>trax client</c> generates from, and how.</summary>
/// <param name="Manifest">The host's client manifest.</param>
/// <param name="Specifier">The module the generated code imports the runtime from.</param>
/// <param name="ToolsDir">The engine's <c>tools/</c>, when the bundled twin generator is not used.</param>
internal sealed record ClientGenerateOptions(
    ClientManifest Manifest,
    string Specifier = ClientGenerator.DefaultSpecifier,
    string? ToolsDir = null
);

/// <summary>One file of a generated client: its path under the output directory, and its text.</summary>
internal sealed record ClientFile(string Path, string Text);

/// <summary>A file that differs between a generated client and the one on disk.</summary>
internal sealed record ClientDrift(string Path, DriftStatus Status);

/// <summary>
/// Generates a frontend's client from a host's <see cref="ClientManifest"/>: for each machine its twin, its
/// persisted documents and a typed hook; for each train a typed function sending its persisted id; the GraphQL types
/// they use; and a check of the client format, which every generated module runs before anything else. The client
/// and its types are rendered here, in C#, so the same manifest always writes the same bytes; the twins come from the
/// engine's own generator, under node. Nothing generated carries a credential: the host's address and the caller's
/// headers are given at run time, to <c>configureTrax</c>.
/// </summary>
internal sealed class ClientGenerator
{
    /// <summary>
    /// The client format this generator writes, held equal to the runtime's <c>clientFormat</c>
    /// (<c>Trax.Api.StateMachine/src/clientFormat.ts</c>) by <c>ClientFormatParityTests</c>.
    /// </summary>
    public const int ClientFormat = 1;

    /// <summary>The module generated code imports the runtime from when none is named.</summary>
    public const string DefaultSpecifier = "@traxsharp/state-machine";

    private const string Header =
        "// Generated by trax client from the host's client manifest. Do not edit.\n";

    private readonly INodeRunner _node;
    private readonly string _bundledToolsDir;

    public ClientGenerator(INodeRunner node, string? bundledToolsDir = null)
    {
        _node = node;
        _bundledToolsDir = bundledToolsDir ?? MachineGenerator.BundledToolsDir;
    }

    /// <summary>Every file of the client, in path order.</summary>
    public IReadOnlyList<ClientFile> Render(ClientGenerateOptions options)
    {
        var manifest = options.Manifest;
        var spec = options.Specifier;
        var files = new List<ClientFile>
        {
            new("format.g.ts", Format(spec)),
            new("client.g.ts", Client(spec)),
            new("manifest.json", ClientManifest.Write(manifest)),
        };
        var names = new Names();
        var sdl = string.IsNullOrWhiteSpace(manifest.Types)
            ? new GraphQLDocument([])
            : Parser.Parse(manifest.Types);
        var types = new SdlTypes(sdl);

        var index = new StringBuilder(Header).Append("import \"./format.g\";\n");
        index.Append(
            "export { configureTrax, TraxOperationError, type TraxConnection } from \"./client.g\";\n"
        );

        // Every name is claimed before anything runs, so a manifest that cannot be generated is refused before node is.
        var machines = new List<(ClientManifestMachine Machine, string Camel, string Pascal)>();
        foreach (var machine in manifest.Machines.OrderBy(m => m.Id, StringComparer.Ordinal))
        {
            if (!MachineGenerator.IsMachineId(machine.Id))
                throw new InvalidOperationException(
                    $"The machine id '{machine.Id}' is not kebab-case, so it cannot name generated files."
                );
            var camel = names.Claim(
                TypeScript.Identifier(TypeScript.Camel(machine.Id), "machine"),
                machine.Id
            );
            var pascal = TypeScript.Pascal(machine.Id);
            names.Claim($"use{pascal}", machine.Id);
            names.Claim($"useRemembered{pascal}", machine.Id);
            names.Claim($"{camel}Server", machine.Id);
            machines.Add((machine, camel, pascal));
        }
        var trains = new List<(ClientManifestTrain Train, string Function)>();
        foreach (
            var train in manifest.Trains.OrderBy(t => t.Documents[0].Id, StringComparer.Ordinal)
        )
        {
            var function = TypeScript.Identifier(
                train.Namespace is null
                    ? train.Field
                    : train.Namespace + TypeScript.Upper(train.Field),
                "train field"
            );
            names.Claim(function, $"the train {train.Field}");
            trains.Add((train, function));
        }

        var progress = Progress(manifest);
        if (progress is not null)
            foreach (var name in ProgressNames)
                names.Claim(name, "runProgress");

        foreach (var (machine, camel, pascal) in machines)
        {
            files.AddRange(Twin(machine, spec, options.ToolsDir));
            files.Add(
                new(
                    $"{machine.Id}/{machine.Id}.client.g.ts",
                    MachineClient(machine, camel, pascal, spec)
                )
            );
            index.Append(
                $"export {{ {camel}, {camel}Server, use{pascal}, useRemembered{pascal} }} from \"./{machine.Id}/{machine.Id}.client.g\";\n"
            );
        }

        if (trains.Count > 0)
        {
            files.Add(new("types.g.ts", types.Render()));
            index.Append("export type * from \"./types.g\";\n");
        }
        foreach (var (train, function) in trains)
        {
            files.Add(new($"trains/{function}.g.ts", Train(train, function, types)));
            index.Append($"export {{ {function} }} from \"./trains/{function}.g\";\n");
        }

        if (progress is { } documents)
        {
            files.Add(
                new("progress.g.ts", ProgressModule(documents.Query, documents.Stream, manifest))
            );
            index.Append(
                $"export {{ {string.Join(", ", ProgressNames)}, type RunProgressView }} from \"./progress.g\";\n"
            );
        }

        files.Add(new("index.g.ts", index.ToString()));
        return files.OrderBy(f => f.Path, StringComparer.Ordinal).ToList();
    }

    /// <summary>Writes the client under <paramref name="outDir"/>, replacing generated files that changed.</summary>
    public IReadOnlyList<ClientFile> Write(ClientGenerateOptions options, string outDir)
    {
        var files = Render(options);
        foreach (var file in files)
        {
            var path = Path.Combine(outDir, file.Path);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, file.Text);
        }
        return files;
    }

    /// <summary>
    /// What differs between the client the manifest generates and the one under <paramref name="outDir"/>: a file
    /// missing or changed, and a generated file (<c>*.g.ts</c>) that would no longer be written. Line endings are not a
    /// difference, so a checkout that writes CRLF passes.
    /// </summary>
    public IReadOnlyList<ClientDrift> Check(ClientGenerateOptions options, string outDir)
    {
        var files = Render(options);
        var drift = new List<ClientDrift>();
        foreach (var file in files)
        {
            var path = Path.Combine(outDir, file.Path);
            if (!File.Exists(path))
                drift.Add(new(file.Path, DriftStatus.Missing));
            else if (File.ReadAllText(path).Replace("\r\n", "\n") != file.Text)
                drift.Add(new(file.Path, DriftStatus.Drifted));
        }
        if (Directory.Exists(outDir))
        {
            var expected = files.Select(f => f.Path).ToHashSet(StringComparer.Ordinal);
            foreach (
                var stale in Directory
                    .EnumerateFiles(outDir, "*.g.ts", SearchOption.AllDirectories)
                    .Select(p => Path.GetRelativePath(outDir, p).Replace('\\', '/'))
                    .Where(p => !expected.Contains(p))
                    .Order(StringComparer.Ordinal)
            )
                drift.Add(new(stale, DriftStatus.Drifted));
        }
        return drift;
    }

    private static string Format(string spec) =>
        Header
        + "// Every generated module imports this first, so a runtime that does not serve this client's format refuses\n"
        + "// it on load, naming both, before any twin is read.\n"
        + $"import {{ requireClientFormat }} from {TypeScript.Literal(spec)};\n\n"
        + $"export const generatedClientFormat = {ClientFormat};\n"
        + "requireClientFormat(generatedClientFormat);\n";

    private static string Client(string spec) =>
        Header
        + "import \"./format.g\";\n"
        + "import { createClient, type Client } from \"graphql-ws\";\n"
        + $"import {{ persistedMessageReplacer }} from {TypeScript.Literal(spec + "/client")};\n"
        + """

            /** Where the host is, and what each request carries. Nothing here is generated: the app gives it at run time. */
            export interface TraxConnection {
              /** The GraphQL endpoint (`https://api.example.com/trax/graphql`). */
              url: string;
              /** The GraphQL socket (`wss://api.example.com/trax/graphql`), for a machine's push. */
              socketUrl: string;
              /** The headers each request carries, read per request so a rotating token stays fresh. */
              headers?: () => Record<string, string>;
              /** What the socket sends in `connection_init`: a browser cannot set headers on a socket. */
              connectionParams?: () => Record<string, unknown> | Promise<Record<string, unknown>>;
            }

            let connection: TraxConnection | null = null;
            let socket: Client | null = null;
            let generation = 0;

            /**
             * Tells the generated client where the host is. Call it before any hook or train function runs, and again when
             * the connection changes (another user signs in): the socket is closed, and every machine's server is made anew
             * on its next use.
             */
            export function configureTrax(next: TraxConnection): void {
              connection = next;
              generation += 1;
              void socket?.dispose();
              socket = null;
            }

            /** How many times configureTrax was called: a machine's server made under an earlier count is made again. */
            export function traxGeneration(): number {
              return generation;
            }

            /** The connection, or a refusal naming what to call. */
            export function traxConnection(): TraxConnection {
              if (!connection) throw new Error("Call configureTrax({ url, socketUrl }) before using the generated client.");
              return connection;
            }

            /** The one socket every push shares, opened with the first subscription. */
            export function traxSocket(): Client {
              const { socketUrl, connectionParams } = traxConnection();
              return (socket ??= createClient({
                url: socketUrl,
                connectionParams,
                lazy: true,
                retryAttempts: Number.POSITIVE_INFINITY,
                jsonMessageReplacer: persistedMessageReplacer,
              }));
            }

            /** A train operation the host refused: `code` is its `extensions.code` (`CLIENT_OUTDATED`, `TRAX_AUTHORIZATION`, ...). */
            export class TraxOperationError extends Error {
              constructor(
                readonly code: string | undefined,
                message: string,
              ) {
                super(message);
                this.name = "TraxOperationError";
              }
            }

            /** Sends a persisted document by its id, never its text, and returns the field at `path` of its answer. */
            export async function sendDocument<T>(id: string, variables: Record<string, unknown>, path: readonly string[]): Promise<T> {
              const { url, headers } = traxConnection();
              const response = await fetch(url, {
                method: "POST",
                headers: { "Content-Type": "application/json", ...headers?.() },
                body: JSON.stringify({ id, variables: withoutUndefined(variables) }),
              });
              const answer = (await response.json()) as {
                data?: Record<string, unknown> | null;
                errors?: { message: string; extensions?: { code?: string } }[];
              };
              const error = answer.errors?.[0];
              if (error) throw new TraxOperationError(error.extensions?.code, error.message);
              let value: unknown = answer.data;
              for (const key of path) value = (value as Record<string, unknown> | null | undefined)?.[key];
              return value as T;
            }

            function withoutUndefined(values: Record<string, unknown>): Record<string, unknown> {
              return Object.fromEntries(Object.entries(values).filter(([, value]) => value !== undefined));
            }

            """;

    private IEnumerable<ClientFile> Twin(
        ClientManifestMachine machine,
        string spec,
        string? toolsDir
    )
    {
        var staging = Path.Combine(Path.GetTempPath(), $"trax-client-{Guid.NewGuid():N}");
        Directory.CreateDirectory(staging);
        try
        {
            var ir = Path.Combine(staging, $"{machine.Id}.ir.json");
            File.WriteAllText(ir, machine.IrText() + "\n");
            var outDir = Path.Combine(staging, "twin");
            Directory.CreateDirectory(outDir);
            var script = Path.Combine(toolsDir ?? _bundledToolsDir, "generate-twin.mjs");
            if (!_node.IsAvailable())
                throw new InvalidOperationException(
                    "Generating a machine's twin needs Node.js 22 or later, and node was not found on PATH (or --node "
                        + "is not an executable)."
                );
            if (!File.Exists(script))
                throw new InvalidOperationException(
                    $"The twin generator is not found at {script}. This trax was built from source, not installed "
                        + "from its package: pass --tools-dir with the engine's tools/ directory."
                );
            var result = _node.Run(
                script,
                [
                    "--ir",
                    ir,
                    "--out-dir",
                    outDir,
                    "--import-style",
                    "specifier",
                    "--specifier",
                    spec,
                ]
            );
            if (result.ExitCode != 0)
                throw new InvalidOperationException(
                    $"node generate-twin.mjs failed (exit {result.ExitCode}): {result.StdErr.Trim()}"
                );
            foreach (var kind in new[] { "contexts", "machine" })
            {
                var file = Path.Combine(outDir, $"{machine.Id}.{kind}.g.ts");
                if (!File.Exists(file))
                    throw new InvalidOperationException($"The twin generator wrote no {file}.");
                yield return new($"{machine.Id}/{machine.Id}.{kind}.g.ts", File.ReadAllText(file));
            }
        }
        finally
        {
            Directory.Delete(staging, recursive: true);
        }
    }

    private static string MachineClient(
        ClientManifestMachine machine,
        string camel,
        string pascal,
        string spec
    )
    {
        var sb = new StringBuilder(Header);
        sb.Append("import \"../format.g\";\n");
        sb.Append(
            $"import {{ createMachineServer, type MachineDocument }} from {TypeScript.Literal(spec + "/client")};\n"
        );
        sb.Append(
            $"import {{ useRememberedMachine, useServerMachine, type UseRememberedMachineOptions, type UseServerMachineOptions }} from {TypeScript.Literal(spec + "/react")};\n"
        );
        sb.Append("import { traxConnection, traxGeneration, traxSocket } from \"../client.g\";\n");
        sb.Append($"import {{ {camel} }} from \"./{machine.Id}.machine.g\";\n\n");
        sb.Append($"export {{ {camel} }};\n\n");
        sb.Append(
            $"/** The persisted documents of '{EscapeDocText(machine.Id)}', by the ids the host registered. */\n"
        );
        sb.Append($"export const {camel}Documents: readonly MachineDocument[] = [\n");
        foreach (
            var document in machine.Documents.OrderBy(d => d.Operation, StringComparer.Ordinal)
        )
            sb.Append("  {\n")
                .Append($"    id: {TypeScript.Literal(document.Id)},\n")
                .Append($"    machine: {TypeScript.Literal(machine.Id)},\n")
                .Append($"    operation: {TypeScript.Literal(document.Operation)},\n")
                .Append($"    irHash: {TypeScript.Literal(machine.IrHash)},\n")
                .Append($"    document: {TypeScript.Literal(document.Document)},\n")
                .Append("  },\n");
        sb.Append("];\n\n");
        sb.Append($"let server: ReturnType<typeof createMachineServer> | null = null;\n");
        sb.Append("let serverGeneration = -1;\n\n");
        sb.Append(
            $"/** The server of '{EscapeDocText(machine.Id)}' over the connection given to configureTrax. */\n"
        );
        sb.Append($"export function {camel}Server(): ReturnType<typeof createMachineServer> {{\n");
        sb.Append("  if (server === null || serverGeneration !== traxGeneration()) {\n");
        sb.Append("    server = createMachineServer(traxConnection().url, {\n");
        sb.Append("      headers: traxConnection().headers,\n");
        sb.Append($"      machine: {camel},\n");
        sb.Append($"      documents: {camel}Documents,\n");
        sb.Append("      socket: traxSocket(),\n");
        sb.Append("    });\n");
        sb.Append("    serverGeneration = traxGeneration();\n");
        sb.Append("  }\n");
        sb.Append("  return server;\n}\n\n");
        sb.Append(
            $"/** One instance of '{EscapeDocText(machine.Id)}': the given id, or one started with `startInput`. */\n"
        );
        sb.Append(
            $"export function use{pascal}(options: Omit<UseServerMachineOptions, \"server\"> = {{}}) {{\n"
        );
        sb.Append(
            $"  return useServerMachine({camel}, {{ ...options, server: {camel}Server() }});\n}}\n\n"
        );
        sb.Append(
            $"/** The instance of '{EscapeDocText(machine.Id)}' this browser keeps across visits, started when there is none. */\n"
        );
        sb.Append(
            $"export function useRemembered{pascal}(options: Omit<UseRememberedMachineOptions, \"server\" | \"rememberKey\"> & {{ rememberKey?: string }} = {{}}) {{\n"
        );
        sb.Append(
            $"  return useRememberedMachine({camel}, {{ rememberKey: {TypeScript.Literal("trax." + machine.Id)}, ...options, server: {camel}Server() }});\n}}\n"
        );
        return sb.ToString();
    }

    private static string Train(ClientManifestTrain train, string function, SdlTypes types)
    {
        var document = train.Documents[0];
        var operation = Parser
            .Parse(document.Document)
            .Definitions.OfType<GraphQLOperationDefinition>()
            .Single();
        var root = train.Root == "mutation" ? "dispatch" : "discover";
        var parentType =
            (train.Namespace is null ? "" : TypeScript.Upper(train.Namespace))
            + (train.Root == "mutation" ? "DispatchMutations" : "DiscoverQueries");
        var answer =
            types.FieldType(parentType, train.Field)
            ?? throw new InvalidOperationException(
                $"The manifest's types do not hold {parentType}.{train.Field}, the answer of the train "
                    + $"'{train.Field}'. Export the manifest again from the host."
            );

        var variables = operation.Variables?.Items ?? [];
        var required = variables
            .Where(v => v.Type is GraphQLNonNullType && v.DefaultValue is null)
            .ToList();
        var optional = variables.Except(required).ToList();

        var parameters = new List<string>();
        foreach (var variable in required)
        {
            var name = TypeScript.Identifier(variable.Variable.Name.StringValue, "variable");
            parameters.Add($"{name}: {types.InputType(variable.Type)}");
        }
        if (optional.Count > 0)
            parameters.Add(
                "options: { "
                    + string.Join(
                        "; ",
                        optional.Select(v =>
                            $"{TypeScript.Identifier(v.Variable.Name.StringValue, "variable")}?: {types.InputType(v.Type)}"
                        )
                    )
                    + " } = {}"
            );
        var values = required
            .Select(v => v.Variable.Name.StringValue)
            .Concat(optional.Count > 0 ? ["...options"] : [])
            .ToList();
        var path = new List<string> { root };
        if (train.Namespace is not null)
            path.Add(train.Namespace);
        path.Add(train.Field);

        var sb = new StringBuilder(Header);
        sb.Append("import \"../format.g\";\n");
        sb.Append("import { sendDocument } from \"../client.g\";\n");
        var used = types
            .NamesIn(variables.Select(v => v.Type))
            .Append(types.NameOf(answer))
            .Where(n => n is not null)
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToList();
        if (used.Count > 0)
            sb.Append($"import type {{ {string.Join(", ", used)} }} from \"../types.g\";\n");
        sb.Append('\n');
        sb.Append(
            $"/** The persisted id of '{EscapeDocText(train.Field)}', which the host registered. */\n"
        );
        sb.Append($"export const {function}DocumentId = {TypeScript.Literal(document.Id)};\n\n");
        sb.Append(TypeScript.Doc(Requirement(train.Requires)));
        sb.Append(
            $"export function {function}({string.Join(", ", parameters)}): Promise<{types.OutputType(answer)}> {{\n"
        );
        sb.Append(
            $"  return sendDocument({function}DocumentId, {(values.Count == 0 ? "{}" : $"{{ {string.Join(", ", values)} }}")}, [{string.Join(", ", path.Select(TypeScript.Literal))}]);\n"
        );
        sb.Append("}\n");
        return sb.ToString();
    }

    private static readonly string[] ProgressNames =
    [
        "readRunProgress",
        "followRunProgress",
        "useRunProgress",
        "runProgressDocumentId",
        "runProgressEventsDocumentId",
    ];

    // The query and the subscription of runProgress, or null when no train lets its starter follow it.
    private static (ClientManifestDocument Query, ClientManifestDocument Stream)? Progress(
        ClientManifest manifest
    )
    {
        if (manifest.Progress.Count == 0)
            return null;
        var query = manifest.Progress.SingleOrDefault(d => d.Operation == "query");
        var stream = manifest.Progress.SingleOrDefault(d => d.Operation == "subscription");
        if (query is null || stream is null || manifest.Progress.Count != 2)
            throw new InvalidOperationException(
                "The manifest's progress documents are not one query and one subscription. Export the manifest "
                    + "again from the host."
            );
        return (query, stream);
    }

    private static string ProgressModule(
        ClientManifestDocument query,
        ClientManifestDocument stream,
        ClientManifest manifest
    )
    {
        var followable = manifest
            .Trains.Where(t => t.Progress)
            .Select(t => t.Namespace is null ? t.Field : $"{t.Namespace}.{t.Field}")
            .Order(StringComparer.Ordinal)
            .ToList();
        var sb = new StringBuilder(Header);
        sb.Append("import \"./format.g\";\n");
        sb.Append("import { useEffect, useState } from \"react\";\n");
        sb.Append("import { sendDocument, traxSocket, TraxOperationError } from \"./client.g\";\n");
        sb.Append("import type { RunProgress, RunProgressEvent } from \"./types.g\";\n\n");
        sb.Append("/** The persisted id of the runProgress query, which the host registered. */\n");
        sb.Append($"export const runProgressDocumentId = {TypeScript.Literal(query.Id)};\n\n");
        sb.Append(
            "/** The persisted id of the runProgress subscription, which the host registered. */\n"
        );
        sb.Append(
            $"export const runProgressEventsDocumentId = {TypeScript.Literal(stream.Id)};\n\n"
        );
        sb.Append(
            TypeScript.Doc(
                "Your run, read once: where it stands and the steps it took. Any run you did not start answers "
                    + "`problem.code` NOT_FOUND. Runs of these trains can be followed: "
                    + string.Join(", ", followable)
                    + "."
            )
        );
        sb.Append(
            """
            export function readRunProgress(runId: string): Promise<RunProgress> {
              return sendDocument(runProgressDocumentId, { runId }, ["runProgress"]);
            }

            /**
             * Follows your run: `onEvent` gets each change of state and each step as it happens, then `onEnd()` once the
             * stream ends, after the run does, or `onEnd(error)` when the host refused it. A `sequence` that skips a number
             * means events were lost: read the run again. Returns the function that stops following.
             */
            export function followRunProgress(
              runId: string,
              onEvent: (event: RunProgressEvent) => void,
              onEnd?: (error?: unknown) => void,
            ): () => void {
              const payload = { query: "", id: runProgressEventsDocumentId, variables: { runId } };
              return traxSocket().subscribe<{ runProgress: RunProgressEvent }>(payload, {
                next: (result) => {
                  const error = result.errors?.[0];
                  if (error) onEnd?.(new TraxOperationError(error.extensions?.code as string | undefined, error.message));
                  else if (result.data) onEvent(result.data.runProgress);
                },
                error: (error) => onEnd?.(error),
                complete: () => onEnd?.(),
              });
            }

            /** A run as useRunProgress shows it. */
            export interface RunProgressView {
              state: RunProgress["state"];
              steps: RunProgress["steps"];
              failure: string | null;
              problem: RunProgress["problem"];
              /** The stream ended: the run ended, or the host refused it. */
              ended: boolean;
            }

            const nothingYet: RunProgressView = { state: null, steps: [], failure: null, problem: null, ended: false };

            /**
             * Your run, kept current: read once, then followed until it ends. A step replaces the one at its position, and
             * a lost event reads the run again. Pass null to follow nothing.
             */
            export function useRunProgress(runId: string | null | undefined): RunProgressView {
              const [view, setView] = useState<RunProgressView>(nothingYet);
              useEffect(() => {
                setView(nothingYet);
                if (!runId) return;
                let live = true;
                let last = 0;
                const read = () =>
                  readRunProgress(runId).then(
                    (run) => {
                      if (live) setView((v) => ({ ...v, state: run.state, steps: run.steps, failure: run.failure, problem: run.problem }));
                    },
                    () => undefined,
                  );
                void read();
                const stop = followRunProgress(
                  runId,
                  (event) => {
                    if (last !== 0 && event.sequence !== last + 1) void read();
                    last = event.sequence;
                    setView((v) => ({
                      ...v,
                      state: event.state ?? v.state,
                      steps: event.step ? withStep(v.steps, event.step) : v.steps,
                      failure: event.failure ?? v.failure,
                      problem: event.problem ?? v.problem,
                    }));
                  },
                  () => {
                    if (live) setView((v) => ({ ...v, ended: true }));
                  },
                );
                return () => {
                  live = false;
                  stop();
                };
              }, [runId]);
              return view;
            }

            type Step = RunProgress["steps"][number];

            function withStep(steps: readonly Step[], step: Step): Step[] {
              const key = (s: Step) => `${s.position}:${s.kind}`;
              const at = steps.findIndex((s) => key(s) === key(step));
              return at < 0 ? [...steps, step] : steps.map((s, i) => (i === at ? step : s));
            }

            """
        );
        return sb.ToString();
    }

    private static string Requirement(ClientManifestRequirement? requires)
    {
        if (requires is null)
            return "";
        if (requires.Anonymous)
            return "Anyone may run it, signed in or not.";
        var parts = new List<string> { "Requires a signed-in caller" };
        foreach (var set in requires.RoleSets)
            parts.Add($"holding one of the roles {string.Join(", ", set)}");
        foreach (var policy in requires.Policies)
            parts.Add($"satisfying the policy {policy}");
        return string.Join(", ", parts) + ". The host checks it either way.";
    }

    private static string EscapeDocText(string text) => text.Replace("*/", "*\\/");

    // The identifiers the client's index exports, so two never collide.
    private sealed class Names
    {
        private readonly Dictionary<string, string> _owners = new(StringComparer.Ordinal);

        public string Claim(string name, string owner)
        {
            if (_owners.TryGetValue(name, out var other) && other != owner)
                throw new InvalidOperationException(
                    $"'{other}' and '{owner}' both generate the name '{name}'. Rename one of them on the host."
                );
            _owners[name] = owner;
            return name;
        }
    }
