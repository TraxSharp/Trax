using System.Security.Cryptography;
using System.Text;
using System.Text.Json.Nodes;
using GraphQLParser;
using GraphQLParser.AST;
using Trax.Cli.Machines;
using Trax.Effect.StateMachine;

namespace Trax.Cli.Clients;

/// <summary>What <c>trax client</c> generates from, and how.</summary>
/// <param name="Manifest">The host's client manifest.</param>
/// <param name="Specifier">The module the generated code imports the runtime from.</param>
/// <param name="ToolsDir">The engine's <c>tools/</c>, when the bundled twin generator is not used.</param>
internal sealed record ClientGenerateOptions(
    ClientManifest Manifest,
    string Specifier = ClientGenerator.DefaultSpecifier,
    string? ToolsDir = null
);

/// <summary>One file of a generated client: its path under the output directory, and its text.</summary>
internal sealed record ClientFile(string Path, string Text);

/// <summary>A file that differs between a generated client and the one on disk.</summary>
internal sealed record ClientDrift(string Path, DriftStatus Status);

/// <summary>
/// Generates a frontend's client from a host's <see cref="ClientManifest"/>: for each machine its twin, its
/// persisted documents and a typed hook; for each train a typed function sending its persisted id; the GraphQL types
/// they use; and a check of the client format, which every generated module runs before anything else. The client
/// and its types are rendered here, in C#, so the same manifest always writes the same bytes; the twins come from the
/// engine's own generator, under node. Nothing generated carries a credential: the host's address and the caller's
/// headers are given at run time, to <c>configureTrax</c>.
/// </summary>
internal sealed class ClientGenerator
{
    /// <summary>
    /// The client format this generator writes, held equal to the runtime's <c>clientFormat</c>
    /// (<c>Trax.Api.StateMachine/src/clientFormat.ts</c>) by <c>ClientFormatParityTests</c>.
    /// </summary>
    public const int ClientFormat = 2;

    /// <summary>The module generated code imports the runtime from when none is named.</summary>
    public const string DefaultSpecifier = "@traxsharp/state-machine";

    private const string Header =
        "// Generated by trax client from the host's client manifest. Do not edit.\n";

    private readonly INodeRunner _node;
    private readonly string _bundledToolsDir;

    public ClientGenerator(INodeRunner node, string? bundledToolsDir = null)
    {
        _node = node;
        _bundledToolsDir = bundledToolsDir ?? MachineGenerator.BundledToolsDir;
    }

    /// <summary>Every file of the client, in path order.</summary>
    public IReadOnlyList<ClientFile> Render(ClientGenerateOptions options)
    {
        var manifest = options.Manifest;
        var spec = options.Specifier;
        var files = new List<ClientFile>
        {
            new("format.g.ts", Format(spec)),
            new("client.g.ts", Client(spec)),
            new("manifest.json", ClientManifest.Write(manifest)),
        };
        var names = new Names();
        foreach (var name in RuntimeNames)
            names.Claim(name, "the client's runtime");
        var types = new SdlTypes(ParseTypes(manifest.Types));

        var index = new StringBuilder(Header).Append("import \"./format.g\";\n");
        index.Append(
            "export { configureTrax, TraxOperationError, type TraxConnection } from \"./client.g\";\n"
        );

        // Every name is claimed before anything runs, so a manifest that cannot be generated is refused before node is.
        var machines = new List<(ClientManifestMachine Machine, string Camel, string Pascal)>();
        foreach (var machine in manifest.Machines.OrderBy(m => m.Id, StringComparer.Ordinal))
        {
            if (!MachineGenerator.IsMachineId(machine.Id))
                throw new InvalidOperationException(
                    $"The machine id '{machine.Id}' is not kebab-case, so it cannot name generated files."
                );
            var camel = names.Claim(
                TypeScript.Identifier(TypeScript.Camel(machine.Id), "machine"),
                machine.Id
            );
            if (MachineModuleNames.Contains(camel))
                throw new InvalidOperationException(
                    $"The machine '{machine.Id}' is written as '{camel}', a name its generated modules use. "
                        + "Rename it on the host."
                );
            var pascal = TypeScript.Pascal(machine.Id);
            names.Claim($"use{pascal}", machine.Id);
            names.Claim($"useRemembered{pascal}", machine.Id);
            names.Claim($"{camel}Server", machine.Id);
            machines.Add((machine, camel, pascal));
        }
        var trains = new List<(string Function, string Text)>();
        // A train's file is claimed by its path in lower case, so two that differ only in case are refused before a
        // case-insensitive disk writes one over the other.
        var paths = new Names(StringComparer.OrdinalIgnoreCase);
        foreach (
            var train in manifest
                .Trains.Select(CheckTrain)
                .OrderBy(t => t.Documents[0].Id, StringComparer.Ordinal)
        )
        {
            var owner =
                $"the {train.Root} train {(train.Namespace is null ? "" : train.Namespace + ".")}{train.Field}";
            var function = TypeScript.Identifier(
                train.Namespace is null
                    ? train.Field
                    : train.Namespace + TypeScript.Upper(train.Field),
                "train field"
            );
            names.Claim(function, owner);
            paths.Claim($"trains/{function}.g.ts", owner);
            trains.Add((function, Train(train, function, types)));
        }
        // types.g.ts is exported from the index beside everything else, so its names are claimed with them.
        if (trains.Count > 0)
            foreach (var type in types.Declared)
                names.Claim(type, $"the GraphQL type {type}");

        var progress = Progress(manifest);
        if (progress is not null)
            foreach (var name in ProgressNames.Append("RunProgressView"))
                names.Claim(name, "runProgress");

        var typesText = trains.Count > 0 ? types.Render() : null;

        // The IR is checked before node reads it: its id names the twin's files, and its names are written as code.
        foreach (var (machine, _, _) in machines)
            CheckIr(machine);

        foreach (var (machine, camel, pascal) in machines)
        {
            files.AddRange(Twin(machine, spec, options.ToolsDir));
            files.Add(
                new(
                    $"{machine.Id}/{machine.Id}.client.g.ts",
                    MachineClient(machine, camel, pascal, spec)
                )
            );
            index.Append(
                $"export {{ {camel}, {camel}Server, use{pascal}, useRemembered{pascal} }} from \"./{machine.Id}/{machine.Id}.client.g\";\n"
            );
        }

        if (typesText is not null)
        {
            files.Add(new("types.g.ts", typesText));
            index.Append("export type * from \"./types.g\";\n");
        }
        foreach (var (function, text) in trains)
        {
            files.Add(new($"trains/{function}.g.ts", text));
            index.Append($"export {{ {function} }} from \"./trains/{function}.g\";\n");
        }

        if (progress is { } documents)
        {
            files.Add(
                new("progress.g.ts", ProgressModule(documents.Query, documents.Stream, manifest))
            );
            index.Append(
                $"export {{ {string.Join(", ", ProgressNames)}, type RunProgressView }} from \"./progress.g\";\n"
            );
        }

        files.Add(new("index.g.ts", index.ToString()));
        return files.OrderBy(f => f.Path, StringComparer.Ordinal).ToList();
    }

    /// <summary>
    /// Writes the client under <paramref name="outDir"/>, replacing generated files that changed. A file this
    /// generator wrote (a client module starting with its header, or the twin of a machine the previous run served)
    /// that the manifest no longer generates is deleted first, then any folder that leaves empty, so a train removed
    /// on the host leaves nothing behind for <c>--check</c> to report. Any other file is left alone, and a linked
    /// folder is not entered. A link at any path the client writes, or at a folder on the way there, is refused
    /// before anything is written.
    /// </summary>
    public IReadOnlyList<ClientFile> Write(ClientGenerateOptions options, string outDir)
    {
        var files = Render(options);
        RefuseLinks(files, outDir);
        foreach (var stale in Stale(files, outDir))
        {
            var path = Path.Combine(outDir, stale);
            File.Delete(path);
            var root = Path.GetFullPath(outDir).TrimEnd(Path.DirectorySeparatorChar);
            for (
                var dir = Path.GetDirectoryName(Path.GetFullPath(path));
                dir is not null
                    && dir.Length > root.Length
                    && dir.StartsWith(root + Path.DirectorySeparatorChar, StringComparison.Ordinal)
                    && !Directory.EnumerateFileSystemEntries(dir).Any();
                dir = Path.GetDirectoryName(dir)
            )
                Directory.Delete(dir);
        }
        foreach (var file in files)
        {
            var path = Path.Combine(outDir, file.Path);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            Replace(path, file.Text);
        }
        return files;
    }

    // Writes the text beside the path and renames it over whatever is there, so a FIFO or a device at the path is
    // replaced rather than opened.
    private static void Replace(string path, string text)
    {
        var temp = Path.Combine(
            Path.GetDirectoryName(path)!,
            $".{Path.GetFileName(path)}.{Guid.NewGuid():N}.tmp"
        );
        try
        {
            File.WriteAllText(temp, text);
            File.Move(temp, path, overwrite: true);
        }
        finally
        {
            File.Delete(temp);
        }
    }

    // Refuses a link at any path the client writes or a folder it creates on the way there: writing through one would
    // put the generated text outside outDir. outDir itself may be a link; nothing under it may.
    private static void RefuseLinks(IReadOnlyList<ClientFile> files, string outDir)
    {
        foreach (var file in files)
        {
            var path = outDir;
            foreach (var part in file.Path.Split('/'))
            {
                path = Path.Combine(path, part);
                if (new FileInfo(path).LinkTarget is not null)
                    throw new InvalidOperationException(
                        $"{path} is a link. trax client writes only real files and folders under --out, never "
                            + "through a link: remove it, or point --out somewhere without one."
                    );
            }
        }
    }

    /// <summary>
    /// What differs between the client the manifest generates and the one under <paramref name="outDir"/>: a file
    /// missing or changed, and a file this generator wrote that would no longer be written. Line endings are not a
    /// difference, so a checkout that writes CRLF passes.
    /// </summary>
    public IReadOnlyList<ClientDrift> Check(ClientGenerateOptions options, string outDir)
    {
        var files = Render(options);
        RefuseLinks(files, outDir);
        var drift = new List<ClientDrift>();
        foreach (var file in files)
        {
            var path = Path.Combine(outDir, file.Path);
            if (!File.Exists(path))
                drift.Add(new(file.Path, DriftStatus.Missing));
            // Twice the text's bytes allows every line ending to be CRLF; anything longer differs anyway.
            else if (
                ReadPrefix(path, 2 * Encoding.UTF8.GetByteCount(file.Text) + 1)
                    ?.Replace("\r\n", "\n") != file.Text
            )
                drift.Add(new(file.Path, DriftStatus.Drifted));
        }
        foreach (var stale in Stale(files, outDir))
            drift.Add(new(stale, DriftStatus.Drifted));
        return drift;
    }

    // The files under outDir this generator wrote and the client no longer holds, by their path under it. A client
    // module is this generator's when its first line is the client's header. A twin is when it sits where this
    // generator puts one, <id>/<id>.machine.g.ts or <id>/<id>.contexts.g.ts, starts with the header the twin generator
    // writes for that id, and <id> is a machine the previous run served: trax machine generate writes the same header,
    // so the header alone does not say which tool wrote it. Anything else, an app's own *.g.ts or another generator's,
    // is left alone. A linked folder is not entered, so nothing outside outDir is read or deleted through it.
    private static IReadOnlyList<string> Stale(IReadOnlyList<ClientFile> files, string outDir)
    {
        if (!Directory.Exists(outDir))
            return [];
        var expected = files.Select(f => f.Path).ToHashSet(StringComparer.Ordinal);
        var served = Served(outDir);
        var enumeration = new EnumerationOptions
        {
            RecurseSubdirectories = true,
            AttributesToSkip = FileAttributes.ReparsePoint,
            MatchCasing = MatchCasing.CaseSensitive,
        };
        return Directory
            .EnumerateFiles(outDir, "*.g.ts", enumeration)
            .Select(p => (Full: p, Path: Path.GetRelativePath(outDir, p).Replace('\\', '/')))
            .Where(f => !expected.Contains(f.Path) && Generated(f.Path, f.Full, served))
            .Select(f => f.Path)
            .Order(StringComparer.Ordinal)
            .ToList();
    }

    // The machines the previous run served: the ids in the manifest.json it wrote under outDir, and each <id>/ that
    // holds a client module with this generator's header. The second matters because the host usually exports its
    // manifest over that manifest.json before trax client runs, so it already names the new set of machines. With
    // neither, no twin is taken for this generator's: a twin left by an earlier run is kept, not deleted.
    private static HashSet<string> Served(string outDir)
    {
        var served = new HashSet<string>(StringComparer.Ordinal);
        var manifest = Path.Combine(outDir, "manifest.json");
        if (ReadPrefix(manifest, ManifestBytes) is { } text)
        {
            try
            {
                if (JsonNode.Parse(text)?["machines"] is JsonArray machines)
                    foreach (var machine in machines)
                        if (
                            machine is JsonObject m
                            && m["id"] is JsonValue id
                            && id.TryGetValue<string>(out var value)
                            && MachineGenerator.IsMachineId(value)
                        )
                            served.Add(value);
            }
            catch (System.Text.Json.JsonException)
            {
                // A manifest.json that is not JSON names no machine.
            }
        }
        var folders = new EnumerationOptions
        {
            AttributesToSkip = FileAttributes.ReparsePoint,
            MatchCasing = MatchCasing.CaseSensitive,
        };
        foreach (var dir in Directory.EnumerateDirectories(outDir, "*", folders))
        {
            var id = Path.GetFileName(dir);
            var client = Path.Combine(dir, $"{id}.client.g.ts");
            if (MachineGenerator.IsMachineId(id) && FirstLine(client) == ClientHeaderLine)
                served.Add(id);
        }
        return served;
    }

    private static readonly string ClientHeaderLine = Header.TrimEnd('\n');

    // The twin generator's first line for each file of a machine's twin.
    private static readonly (string Kind, string Generator)[] TwinFiles =
    [
        ("machine", "generateMachineFactory"),
        ("contexts", "generateContextTypes"),
    ];

    private static bool Generated(string relative, string path, IReadOnlySet<string> served)
    {
        var first = FirstLine(path);
        if (first is null)
            return false;
        if (first == ClientHeaderLine)
            return true;
        return relative.Split('/') is [var id, var name]
            && served.Contains(id)
            && TwinFiles.Any(t =>
                name == $"{id}.{t.Kind}.g.ts"
                && first
                    == $"// AUTO-GENERATED from {id}.ir.json by {t.Generator}. Do not edit by hand."
            );
    }

    // The most of a file read to find its first line: longer than any header, so a first line cut here is not one.
    private const int HeaderBytes = 4096;

    // The most of a previous run's manifest.json read: one larger is cut short, is not JSON, and names no machine.
    private const int ManifestBytes = 64 * 1024 * 1024;

    // The first line of a file, without its line ending, read from at most HeaderBytes of it; null when it is not a
    // regular file or is empty.
    private static string? FirstLine(string path)
    {
        var text = ReadPrefix(path, HeaderBytes);
        if (string.IsNullOrEmpty(text))
            return null;
        var end = text.IndexOf('\n', StringComparison.Ordinal);
        return (end < 0 ? text : text[..end]).TrimEnd('\r');
    }

    // At most `limit` bytes of a file, as UTF-8, or null when it is not a regular file. .NET reports a FIFO, a socket
    // or a device as an ordinary file of length 0, and opening a FIFO blocks until something writes to it, so a file
    // of length 0 is not opened (it holds nothing to read either), and one that opens unseekable is not read.
    private static string? ReadPrefix(string path, int limit)
    {
        var info = new FileInfo(path);
        if (!info.Exists || info.LinkTarget is not null)
            return null;
        if (info.Length == 0)
            return "";
        using var stream = new FileStream(
            path,
            FileMode.Open,
            FileAccess.Read,
            FileShare.ReadWrite
        );
        if (!stream.CanSeek)
            return null;
        var buffer = new byte[(int)Math.Min(limit, stream.Length)];
        stream.ReadExactly(buffer);
        return Encoding.UTF8.GetString(buffer);
    }

    // The names a machine's client module and its twin declare or import beside the machine's own, which its camel id
    // would hide or redeclare.
    private static readonly HashSet<string> MachineModuleNames = new(StringComparer.Ordinal)
    {
        "server",
        "serverGeneration",
        "queueMicrotask",
        "subscribeTrax",
        "traxConnection",
        "traxGeneration",
        "traxSocket",
        "createMachineServer",
        "useServerMachine",
        "useRememberedMachine",
        "useSyncExternalStore",
        "generation",
        "connection",
        "socket",
        "changed",
        "startStorageKey",
        "user",
        "rememberKey",
        "key",
        "options",
        "ir",
        "irHash",
        "typedMachineFromIr",
    };

    // The names the client's own modules export from the index, which no machine, train or type may take.
    private static readonly string[] RuntimeNames =
    [
        "configureTrax",
        "TraxOperationError",
        "TraxConnection",
    ];

    // The SDL of the manifest's types, or a refusal saying the manifest is malformed.
    private static GraphQLDocument ParseTypes(string? types)
    {
        if (string.IsNullOrWhiteSpace(types))
            return new GraphQLDocument([]);
        try
        {
            return Parser.Parse(types);
        }
        catch (GraphQLParser.Exceptions.GraphQLParserException ex)
        {
            throw new InvalidOperationException(
                $"The manifest's types are not GraphQL SDL ({ex.Message.Trim()}). Export the manifest again from the "
                    + "host.",
                ex
            );
        }
    }

    // A train the generator can write: a root it knows and one document, which names its operation.
    private static ClientManifestTrain CheckTrain(ClientManifestTrain train)
    {
        if (train.Root is not ("mutation" or "query"))
            throw new InvalidOperationException(
                $"The train '{train.Field}' is under the root '{train.Root}', which is neither mutation nor query. "
                    + "Export the manifest again from the host."
            );
        if (train.Documents.Count != 1)
            throw new InvalidOperationException(
                $"The train '{train.Field}' has {train.Documents.Count} documents where it has one. Export the "
                    + "manifest again from the host."
            );
        return train;
    }

    /// <summary>
    /// Refuses an IR the twin generator must not read: one naming another machine than the manifest entry (its id
    /// names the twin's files), one whose state, trigger or outcome names are not identifiers (they are written into
    /// the twin as code), one whose context, invariants or inputs are keyed by something other than its states and
    /// triggers, one holding a <c>__proto__</c> key (the twin's object literal would make it a prototype, so the twin's
    /// IR would differ from the one hashed), and one whose SHA-256 is not the
    /// <see cref="ClientManifestMachine.IrHash"/> its documents carry.
    /// </summary>
    private static void CheckIr(ClientManifestMachine machine)
    {
        var ir = machine.Ir;
        var id = ir["id"] is JsonValue value && value.TryGetValue<string>(out var s) ? s : null;
        if (id != machine.Id)
            throw new InvalidOperationException(
                $"The IR of the machine '{machine.Id}' is the IR of '{id}'. Export the manifest again from the host."
            );
        var declared = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var (key, what) in new[] { ("states", "state"), ("triggers", "trigger") })
        {
            var names = declared[what] = new HashSet<string>(StringComparer.Ordinal);
            if (ir[key] is not JsonArray list)
                throw new InvalidOperationException(
                    $"The IR of the machine '{machine.Id}' has no {key}. Export the manifest again from the host."
                );
            foreach (var item in list)
                if (
                    item is not JsonValue v
                    || !v.TryGetValue<string>(out var name)
                    || !TypeScript.IsIdentifier(name)
                )
                    throw NotAnIdentifier(machine.Id, what, item?.ToJsonString());
                else if (TypeScript.IsPrototypeMember(name))
                    throw new InvalidOperationException(
                        $"The machine '{machine.Id}' has the {what} {TypeScript.Literal(name)}, a name every "
                            + "JavaScript object has, so the twin would read it as something else. Rename it on the host."
                    );
                else
                    names.Add(name);
        }
        // The twin looks a state's context and invariant, and a trigger's input, up by name: a key that is none of them
        // is not the host's.
        foreach (
            var (key, what) in new[]
            {
                ("context", "state"),
                ("invariants", "state"),
                ("inputs", "trigger"),
            }
        )
        {
            if (ir[key] is not (null or JsonObject))
                throw new InvalidOperationException(
                    $"The IR of the machine '{machine.Id}' has {key} that are not an object. Export the manifest "
                        + "again from the host."
                );
            foreach (var (name, _) in ir[key] as JsonObject ?? [])
                if (!declared[what].Contains(name))
                    throw new InvalidOperationException(
                        $"The IR of the machine '{machine.Id}' has {key} for {TypeScript.Literal(name)}, which is not "
                            + $"one of its {what}s. Export the manifest again from the host."
                    );
        }
        if (HasProtoKey(ir))
            throw new InvalidOperationException(
                $"The IR of the machine '{machine.Id}' has a key \"__proto__\", which the twin's object literal would "
                    + "read as its prototype. Rename the member it names on the host, or export the manifest again."
            );
        if (ir["outcomes"] is not (null or JsonObject))
            throw new InvalidOperationException(
                $"The IR of the machine '{machine.Id}' has outcomes that are not an object. Export the manifest "
                    + "again from the host."
            );
        // An outcome is <State>.<kind> (Fetching.done): each half is written into a type name.
        foreach (var (name, _) in ir["outcomes"] as JsonObject ?? [])
            if (
                name.Split('.') is not [var state, var kind]
                || !TypeScript.IsIdentifier(state)
                || !TypeScript.IsIdentifier(kind)
            )
                throw NotAnIdentifier(machine.Id, "outcome", name);

        var hash = Convert.ToHexStringLower(
            SHA256.HashData(Encoding.UTF8.GetBytes(machine.IrText()))
        );
        if (hash != machine.IrHash)
            throw new InvalidOperationException(
                $"The IR of the machine '{machine.Id}' hashes to {hash}, and the manifest names {machine.IrHash}: "
                    + "its documents were registered for another IR. Export the manifest again from the host."
            );
    }

    private static bool HasProtoKey(JsonNode? node) =>
        node switch
        {
            JsonObject o => o.Any(p => p.Key == "__proto__" || HasProtoKey(p.Value)),
            JsonArray a => a.Any(HasProtoKey),
            _ => false,
        };

    private static InvalidOperationException NotAnIdentifier(
        string machine,
        string what,
        string? name
    ) =>
        new(
            $"The machine '{machine}' has the {what} {name}, which is not an identifier, so it cannot be written "
                + "into its twin. Rename it on the host."
        );

    private static string Format(string spec) =>
        Header
        + "// Every generated module imports this first, so a runtime that does not serve this client's format refuses\n"
        + "// it on load, naming both, before any twin is read.\n"
        + $"import {{ requireClientFormat }} from {TypeScript.Literal(spec)};\n\n"
        + $"export const generatedClientFormat = {ClientFormat};\n"
        + "requireClientFormat(generatedClientFormat);\n";

    private static string Client(string spec) =>
        Header
        + "import \"./format.g\";\n"
        + "import { createClient, type Client } from \"graphql-ws\";\n"
        + $"import {{ persistedMessageReplacer }} from {TypeScript.Literal(spec + "/client")};\n"
        + """

            /** Where the host is, and what each request carries. Nothing here is generated: the app gives it at run time. */
            export interface TraxConnection {
              /** The GraphQL endpoint (`https://api.example.com/trax/graphql`). */
              url: string;
              /** The GraphQL socket (`wss://api.example.com/trax/graphql`), for a machine's push. */
              socketUrl: string;
              /** The headers each request carries, read per request so a rotating token stays fresh. */
              headers?: () => Record<string, string>;
              /** What the socket sends in `connection_init`: a browser cannot set headers on a socket. */
              connectionParams?: () => Record<string, unknown> | Promise<Record<string, unknown>>;
              /**
               * The signed-in user's id. A remembered machine is kept under it, so a browser two people sign in to never
               * opens one's instance for the other, and a start in flight is never sent again as another user. Given here,
               * with the headers, so the two cannot disagree for a render.
               */
              user?: string;
            }

            let connection: TraxConnection | null = null;
            let socket: Client | null = null;
            let generation = 0;
            const listeners = new Set<() => void>();

            /**
             * Tells the generated client where the host is and who is signed in. Call it before any hook or train function
             * runs, and again when the connection changes (another user signs in): the socket is closed, a machine's server
             * made before refuses to send, every machine's server is made anew on its next use, and every mounted machine
             * hook renders again onto it.
             */
            export function configureTrax(next: TraxConnection): void {
              connection = next;
              generation += 1;
              const closing = socket;
              socket = null;
              void closing?.dispose();
              for (const listener of [...listeners]) listener();
            }

            /** How many times configureTrax was called: a machine's server made under an earlier count is made again. */
            export function traxGeneration(): number {
              return generation;
            }

            /** Calls `listener` after each configureTrax, until the function it returns is called. The machine hooks render on it. */
            export function subscribeTrax(listener: () => void): () => void {
              listeners.add(listener);
              return () => {
                listeners.delete(listener);
              };
            }

            /** The connection, or a refusal naming what to call. */
            export function traxConnection(): TraxConnection {
              if (!connection) throw new Error("Call configureTrax({ url, socketUrl }) before using the generated client.");
              return connection;
            }

            /** The one socket every push shares, opened with the first subscription. */
            export function traxSocket(): Client {
              const { socketUrl, connectionParams } = traxConnection();
              return (socket ??= createClient({
                url: socketUrl,
                connectionParams,
                lazy: true,
                retryAttempts: Number.POSITIVE_INFINITY,
                jsonMessageReplacer: persistedMessageReplacer,
              }));
            }

            /** A train operation the host refused: `code` is its `extensions.code` (`CLIENT_OUTDATED`, `TRAX_AUTHORIZATION`, ...). */
            export class TraxOperationError extends Error {
              readonly code: string | undefined;

              constructor(code: string | undefined, message: string) {
                super(message);
                this.name = "TraxOperationError";
                this.code = code;
              }
            }

            /** Sends a persisted document by its id, never its text, and returns the field at `path` of its answer. */
            export async function sendDocument<T>(id: string, variables: Record<string, unknown>, path: readonly string[]): Promise<T> {
              const { url, headers } = traxConnection();
              const response = await fetch(url, {
                method: "POST",
                headers: { "Content-Type": "application/json", ...headers?.() },
                body: JSON.stringify({ id, variables: withoutUndefined(variables) }),
              });
              const answer = (await response.json()) as {
                data?: Record<string, unknown> | null;
                errors?: { message: string; extensions?: { code?: string } }[];
              };
              const error = answer.errors?.[0];
              if (error) throw new TraxOperationError(error.extensions?.code, error.message);
              let value: unknown = answer.data;
              for (const key of path) value = (value as Record<string, unknown> | null | undefined)?.[key];
              return value as T;
            }

            function withoutUndefined(values: Record<string, unknown>): Record<string, unknown> {
              return Object.fromEntries(Object.entries(values).filter(([, value]) => value !== undefined));
            }

