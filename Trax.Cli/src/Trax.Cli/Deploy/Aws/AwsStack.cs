using System.Globalization;
using System.Text.Json;
using System.Text.Json.Nodes;
using Trax.Core.Extensions;
using Trax.Effect.Configuration.Deploy;

namespace Trax.Cli.Deploy.Aws;

/// <summary>
/// The CloudFormation templates of one environment, generated from <c>trax.deploy.json</c> and what each host
/// reports, so the stacks follow the code. The <b>foundation</b> holds what outlives a runtime and what a Kubernetes
/// cluster on AWS would share: the network, the database and its secret, the sign-in, and the security group a
/// client of the database wears. The <b>runtime</b> runs the app on ECS on top of it: the load balancer, the cluster,
/// the roles, the tasks and the services. The runtime reads the foundation through parameters the deployer fills from
/// the foundation's outputs, never through exports, so the foundation stays free to change what it outputs. Nothing
/// secret is in either: the database password is generated by Secrets Manager and every secret reaches a task by
/// reference.
/// </summary>
internal static partial class AwsStack
{
    public const string MigrateImageParameter = "MigrateImage";

    /// <summary>Production only: "true" keeps the database from being deleted, until destroy turns it off.</summary>
    public const string ProtectParameter = "Protect";

    /// <summary>
    /// Production with Cognito only: the id of a user pool an earlier destroy kept, which the stack signs in against
    /// instead of creating one; empty to create one.
    /// </summary>
    public const string UserPoolParameter = "ExistingUserPool";

    public const string MigrateContainer = "migrate";

    /// <summary>The address range of a VPC the stack creates; also the networks hosts trust forwarded headers from.</summary>
    public const string VpcCidr = "10.0.0.0/16";

    public const int ContainerPort = 8080;

    /// <summary>
    /// The Postgres a new database starts on. RDS refuses a bare major version for a new instance, so this names a
    /// minor; minor upgrades after that are RDS's (AutoMinorVersionUpgrade).
    /// </summary>
    public const string PostgresVersion = "17.11";

    public const string DatabaseUser = "trax";

    /// <summary>
    /// Where the image carries the CAs that sign every RDS server certificate. Trax.Effect.Data.Postgres copies the
    /// bundle to <c>trax/</c> in the app's publish output, which <c>-t:PublishContainer</c> puts in <c>/app</c>.
    /// </summary>
    public const string RdsCaBundle = "/app/trax/rds-global-bundle.pem";

    /// <summary>
    /// The foundation's outputs a runtime takes as parameters of the same name. The deployer passes each one the
    /// runtime template declares.
    /// </summary>
    public static readonly IReadOnlySet<string> FoundationValues = new HashSet<string>(
        StringComparer.Ordinal
    )
    {
        "VpcId",
        "VpcCidr",
        "PublicSubnets",
        "ServiceSubnets",
        "DatabaseClientSecurityGroup",
        "DatabaseAddress",
        "DatabasePort",
        "DatabaseSecretArn",
        "UserPoolId",
        "UserPoolClientId",
    };

    // AWS managed policies and CloudFront managed policies, by their fixed ids.
    private const string TaskExecutionPolicy =
        "arn:aws:iam::aws:policy/service-role/AmazonECSTaskExecutionRolePolicy";
    private const string CachingDisabledPolicy = "4135ea2d-6df8-44a3-9df3-4b5a84be39ad";
    private const string AllViewerOriginRequestPolicy = "216adef6-5c7f-47e4-b989-5492eafa07d3";

    /// <summary>The template parameter carrying <paramref name="service"/>'s image.</summary>
    public static string ImageParameter(string service) => $"{LogicalId(service)}Image";

    /// <summary>
    /// The template parameter carrying how many copies of <paramref name="service"/> run: "0" while its image waits
    /// for a migration.
    /// </summary>
    public static string CountParameter(string service) => $"{LogicalId(service)}Count";

    /// <summary>The ECS service of <paramref name="service"/>, as the stack's output names it.</summary>
    public static string ServiceOutput(string service) => $"{LogicalId(service)}ServiceName";

    /// <summary>
    /// Builds both templates. <paramref name="cloudFrontPrefixList"/> is the region's CloudFront origin-facing prefix
    /// list, which the try profile's load balancer admits; it is not read for production.
    /// </summary>
    public static AwsTemplates Build(
        DeployFile file,
        string environmentName,
        IReadOnlyDictionary<string, DeployManifest> exports,
        string? cloudFrontPrefixList
    )
    {
        var env = file.Environment(environmentName);
        Check(file, env, exports);
        var production = string.Equals(
            env.Profile,
            DeployEnvironment.Production,
            StringComparison.Ordinal
        );
        var api = ApiService(file, exports, production, cloudFrontPrefixList);
        return new AwsTemplates(
            Foundation(file, environmentName, env, production),
            Runtime(file, environmentName, env, exports, api, production, cloudFrontPrefixList)
        );
    }

    /// <summary>
    /// The network, the database, its secret and the group its clients wear, and the sign-in. Its stack is
    /// <see cref="DeployFile.FoundationStackName"/>, but every name inside it is the environment's
    /// (<see cref="DeployFile.StackName"/>), so the secrets and the records keep the names they had.
    /// </summary>
    private static JsonObject Foundation(
        DeployFile file,
        string environmentName,
        DeployEnvironment env,
        bool production
    )
    {
        var stack = file.StackName(environmentName);
        var resources = new JsonObject();
        var outputs = new JsonObject();
        var parameters = new JsonObject();
        if (production && env.DatabaseSecretArn is null)
            parameters[ProtectParameter] = new JsonObject
            {
                ["Type"] = "String",
                ["AllowedValues"] = new JsonArray("true", "false"),
                ["Default"] = "true",
                ["Description"] =
                    "Whether the database refuses to be deleted. trax deploy destroy sets it to false first.",
            };

        // ---- Network -------------------------------------------------------------------------------------
        var (vpc, cidr, publicSubnets, serviceSubnets) = Network(resources, stack, env, production);

        // ---- The database, and the one group allowed to reach it ---------------------------------------------
        var securityGroups = AddDatabaseAndClients(
            resources,
            outputs,
            stack,
            env,
            production,
            vpc,
            serviceSubnets
        );

        // ---- Sign-in ---------------------------------------------------------------------------------------
        if (env.Auth is { Kind: DeployAuth.Cognito })
            AddCognito(resources, outputs, parameters, stack, production);

        outputs["VpcId"] = Output(vpc.DeepClone());
        outputs["VpcCidr"] = Output(cidr.DeepClone());
        outputs["OwnsVpc"] = Output(env.Network is null ? "true" : "false");
        outputs["PublicSubnets"] = Output(Join(",", publicSubnets));
        outputs["ServiceSubnets"] = Output(Join(",", serviceSubnets));
        outputs["DatabaseClientSecurityGroup"] = Output(Ref("DatabaseClientSecurityGroup"));
        outputs["SecurityGroups"] = Output(Join(",", securityGroups));

        return Template(
            $"Trax app {file.App}, environment {environmentName} ({env.Profile}): the network, database, secrets "
                + "and sign-in. Written by trax deploy; changes made outside it are reverted on the next deploy.",
            parameters,
            resources,
            outputs
        );
    }

    /// <summary>
    /// The database, when the stack creates one, and the group whatever runs the app (ECS tasks, or a Kubernetes
    /// cluster's pods) wears to reach it. The group lives in the foundation, not a runtime, so the database's rule
    /// never names something created after it. Returns the security groups the foundation creates.
    /// </summary>
    private static JsonArray AddDatabaseAndClients(
        JsonObject resources,
        JsonObject outputs,
        string stack,
        DeployEnvironment env,
        bool production,
        JsonNode vpc,
        JsonArray serviceSubnets
    )
    {
        var securityGroups = new JsonArray(Ref("DatabaseClientSecurityGroup"));
        if (env.DatabaseSecretArn is not null)
        {
            resources["DatabaseClientSecurityGroup"] = SecurityGroup(
                stack,
                vpc,
                ClientsOfTheDatabase,
                [
                    Rule(
                        "tcp",
                        5432,
                        5432,
                        cidr: "0.0.0.0/0",
                        description: "The existing Postgres database"
                    ),
                ]
            );
            return securityGroups;
        }
        AddDatabaseSecurityGroups(resources, stack, vpc);
        securityGroups.Add(Ref("DatabaseSecurityGroup"));
        AddDatabase(resources, stack, production, serviceSubnets);
        outputs["DatabaseAddress"] = Output(GetAtt("Database", "Endpoint.Address"));
        outputs["DatabasePort"] = Output(GetAtt("Database", "Endpoint.Port"));
        outputs["DatabaseSecretArn"] = Output(Ref("DatabaseSecret"));
        return securityGroups;
    }

    /// <summary>The ECS runtime: load balancer, cluster, roles, tasks and services, over the foundation.</summary>
    private static JsonObject Runtime(
        DeployFile file,
        string environmentName,
        DeployEnvironment env,
        IReadOnlyDictionary<string, DeployManifest> exports,
        string? api,
        bool production,
        string? cloudFrontPrefixList
    )
    {
        var stack = file.StackName(environmentName);
        var resources = new JsonObject();
        var outputs = new JsonObject();
        var parameters = RuntimeParameters(file, env, api);
        var vpc = Ref("VpcId");
        var serviceSubnets = Ref("ServiceSubnets");
        // A service in a public subnet reaches ECR, Secrets Manager and the logs through its own public address;
        // its security group admits nothing from outside the load balancer.
        var assignPublicIp = production || env.Network is not null ? "DISABLED" : "ENABLED";

        // ---- The tasks' own group: the default allow-all egress is replaced ---------------------------------
        AddTaskSecurityGroup(resources, stack, vpc);
        var taskGroups = new JsonArray(
            Ref("TaskSecurityGroup"),
            Ref("DatabaseClientSecurityGroup")
        );
        var securityGroups = new JsonArray(Ref("TaskSecurityGroup"));

        // ---- Load balancer, TLS and the address -------------------------------------------------------------
        if (api is not null)
        {
            AddLoadBalancer(
                resources,
                outputs,
                stack,
                env,
                exports[api],
                vpc,
                Ref("PublicSubnets"),
                production,
                cloudFrontPrefixList
            );
            securityGroups.Add(Ref("LoadBalancerSecurityGroup"));
        }

        // ---- ECS -------------------------------------------------------------------------------------------
        AddEcs(
            resources,
            outputs,
            file,
            stack,
            env,
            exports,
            api,
            new ServiceNetwork(serviceSubnets, taskGroups, assignPublicIp),
            production
        );
        outputs["SecurityGroups"] = Output(Join(",", securityGroups));
        return Template(
            $"Trax app {file.App}, environment {environmentName} ({env.Profile}): the ECS services. Written by "
                + "trax deploy; changes made outside it are reverted on the next deploy.",
            parameters,
            resources,
            outputs
        );
    }

    // The cluster, its roles, the migrate task and the services, with the outputs the deployer reads.
    private static void AddEcs(
        JsonObject resources,
        JsonObject outputs,
        DeployFile file,
        string stack,
        DeployEnvironment env,
        IReadOnlyDictionary<string, DeployManifest> exports,
        string? api,
        ServiceNetwork network,
        bool production
    )
    {
        AddClusterAndExecutionRole(resources, file, env, stack);
        var environment = TaskEnvironment(file, env);
        var secrets = TaskSecrets(file, env, stack);
        var migrator = Migrator(file, exports);
        AddMigrateTask(resources, outputs, stack, environment, secrets);
        AddServices(
            resources,
            outputs,
            file,
            stack,
            api,
            environment,
            secrets,
            network,
            production
        );
        AddClusterOutputs(
            outputs,
            network.Subnets,
            network.SecurityGroups,
            network.AssignPublicIp,
            migrator
        );
    }

    // The service the load balancer serves: the one with the api role, if any.
    private static string? ApiService(
        DeployFile file,
        IReadOnlyDictionary<string, DeployManifest> exports,
        bool production,
        string? cloudFrontPrefixList
    )
    {
        var api = file.Services.Keys.FirstOrDefault(s => exports[s].Roles.Contains("api"));
        if (!production && api is not null && cloudFrontPrefixList is null)
            throw new InvalidOperationException(
                "The try profile admits only CloudFront to its load balancer, and the region's CloudFront prefix "
                    + "list was not found."
            );
        return api;
    }

    private static void AddMigrateTask(
        JsonObject resources,
        JsonObject outputs,
        string stack,
        List<(string Name, JsonNode Value)> environment,
        List<(string Name, JsonNode From)> secrets
    )
    {
        AddTask(
            resources,
            stack,
            MigrateContainer,
            Ref(MigrateImageParameter),
            environment,
            secrets,
            port: false,
            command: TraxMigrate.Argument
        );
        outputs["MigrateTaskDefinition"] = Output(Ref("MigrateTaskDefinition"));
        outputs["MigrateContainer"] = Output(MigrateContainer);
    }

    private static void AddClusterOutputs(
        JsonObject outputs,
        JsonNode serviceSubnets,
        JsonArray taskGroups,
        string assignPublicIp,
        string migrator
    )
    {
        outputs["ClusterName"] = Output(Ref("Cluster"));
        outputs["ServiceSubnets"] = Output(Join(",", serviceSubnets.DeepClone()));
        outputs["TaskSecurityGroups"] = Output(Join(",", taskGroups.DeepClone()));
        outputs["AssignPublicIp"] = Output(assignPublicIp);
        outputs["Migrator"] = Output(migrator);
    }

    private static JsonObject RuntimeParameters(DeployFile file, DeployEnvironment env, string? api)
    {
        var parameters = new JsonObject
        {
            [MigrateImageParameter] = new JsonObject
            {
                ["Type"] = "String",
                ["Description"] =
                    "The image the migrate task runs: the new version of the API service.",
            },
        };
        foreach (var service in file.Services.Keys)
        {
            parameters[ImageParameter(service)] = new JsonObject
            {
                ["Type"] = "String",
                ["Description"] = $"The image the {service} service runs.",
            };
            parameters[CountParameter(service)] = new JsonObject
            {
                ["Type"] = "Number",
                ["MinValue"] = 0,
                ["Default"] = file.Count(env, service).ToString(CultureInfo.InvariantCulture),
                ["Description"] =
                    $"How many copies of {service} run. 0 while its image waits for the migration, so it never "
                    + "starts on a schema older than it.",
            };
        }
        AddFoundationParameters(parameters, env, api);
        return parameters;
    }

    // What the foundation gives, as parameters the deployer fills from its outputs.
    private static void AddFoundationParameters(
        JsonObject parameters,
        DeployEnvironment env,
        string? api
    )
    {
        void From(string name, string type, string description) =>
            parameters[name] = new JsonObject
            {
                ["Type"] = type,
                ["Description"] = $"From the foundation stack: {description}",
            };
        From("VpcId", "String", "the VPC.");
        From("VpcCidr", "String", "the VPC's address range.");
        From("ServiceSubnets", "CommaDelimitedList", "the subnets the services run in.");
        From(
            "DatabaseClientSecurityGroup",
            "String",
            "the group a task wears to reach the database."
        );
        if (api is not null)
            From("PublicSubnets", "CommaDelimitedList", "the load balancer's subnets.");
        if (env.DatabaseSecretArn is null)
        {
            From("DatabaseAddress", "String", "the database's host name.");
            From("DatabasePort", "String", "the database's port.");
            From("DatabaseSecretArn", "String", "the secret holding the database's password.");
        }
        if (env.Auth is { Kind: DeployAuth.Cognito })
        {
            From("UserPoolId", "String", "the Cognito user pool.");
            From("UserPoolClientId", "String", "the user pool's app client.");
        }
    }

    private static (
        JsonNode Vpc,
        JsonNode Cidr,
        JsonArray PublicSubnets,
        JsonArray ServiceSubnets
    ) Network(JsonObject resources, string stack, DeployEnvironment env, bool production)
    {
        if (env.Network is { } network)
            return (
                network.VpcId,
                network.Cidr,
                [.. network.PublicSubnets.Select(s => (JsonNode)s)],
                [.. network.PrivateSubnets.Select(s => (JsonNode)s)]
            );
        AddVpc(resources, stack, production);
        return (
            Ref("Vpc"),
            VpcCidr,
            [Ref("PublicSubnetA"), Ref("PublicSubnetB")],
            production
                ? [Ref("PrivateSubnetA"), Ref("PrivateSubnetB")]
                : [Ref("PublicSubnetA"), Ref("PublicSubnetB")]
        );
    }

    private static void AddTaskSecurityGroup(JsonObject resources, string stack, JsonNode vpc) =>
        resources["TaskSecurityGroup"] = SecurityGroup(
            stack,
            vpc,
            "The Trax services",
            [
                Rule(
                    "tcp",
                    443,
                    443,
                    cidr: "0.0.0.0/0",
                    description: "AWS APIs and the app's own outbound HTTPS"
                ),
            ]
        );

    // One description whichever database the clients reach: a new description replaces the group, and running tasks
    // wear it.
    private const string ClientsOfTheDatabase = "Clients of the Postgres database";

    // The database's group admits its clients alone and sends nothing out; the clients' group reaches it alone.
    private static void AddDatabaseSecurityGroups(JsonObject resources, string stack, JsonNode vpc)
    {
        resources["DatabaseClientSecurityGroup"] = SecurityGroup(
            stack,
            vpc,
            ClientsOfTheDatabase,
            [
                Rule(
                    "-1",
                    from: null,
                    to: null,
                    cidr: "127.0.0.1/32",
                    description: "Replaced by the rule to the database"
                ),
            ]
        );
        resources["DatabaseSecurityGroup"] = SecurityGroup(
            stack,
            vpc,
            "The Postgres database",
            [Rule("-1", from: null, to: null, cidr: "127.0.0.1/32", description: "No egress")]
        );
        resources["DatabaseClientToDatabase"] = Resource(
            "AWS::EC2::SecurityGroupEgress",
            new JsonObject
            {
                ["GroupId"] = Ref("DatabaseClientSecurityGroup"),
                ["IpProtocol"] = "tcp",
                ["FromPort"] = 5432,
                ["ToPort"] = 5432,
                ["DestinationSecurityGroupId"] = Ref("DatabaseSecurityGroup"),
                ["Description"] = "Postgres",
            }
        );
        resources["DatabaseFromClients"] = Resource(
            "AWS::EC2::SecurityGroupIngress",
            new JsonObject
            {
                ["GroupId"] = Ref("DatabaseSecurityGroup"),
                ["IpProtocol"] = "tcp",
                ["FromPort"] = 5432,
                ["ToPort"] = 5432,
                ["SourceSecurityGroupId"] = Ref("DatabaseClientSecurityGroup"),
                ["Description"] = "Clients of the database",
            }
        );
    }

    private static void AddClusterAndExecutionRole(
        JsonObject resources,
        DeployFile file,
        DeployEnvironment env,
        string stack
    )
    {
        resources["Cluster"] = Resource(
            "AWS::ECS::Cluster",
            new JsonObject { ["ClusterName"] = stack }
        );
        resources["TaskExecutionRole"] = Resource(
            "AWS::IAM::Role",
            new JsonObject
            {
                ["AssumeRolePolicyDocument"] = AssumedByTasks(),
                ["ManagedPolicyArns"] = new JsonArray(TaskExecutionPolicy),
                ["Policies"] = new JsonArray(
                    new JsonObject
                    {
                        ["PolicyName"] = "read-the-stacks-secrets",
                        ["PolicyDocument"] = new JsonObject
                        {
                            ["Version"] = "2012-10-17",
                            ["Statement"] = new JsonArray(
                                new JsonObject
                                {
                                    ["Effect"] = "Allow",
                                    ["Action"] = new JsonArray("secretsmanager:GetSecretValue"),
                                    ["Resource"] = SecretResources(file, env, stack),
                                }
                            ),
                        },
                    }
                ),
            }
        );
    }

    private static List<(string Name, JsonNode Value)> TaskEnvironment(
        DeployFile file,
        DeployEnvironment env
    )
    {
        var environment = new List<(string Name, JsonNode Value)>
        {
            ("Trax__Proxy__KnownNetworks", Ref("VpcCidr")),
        };
        if (env.DatabaseSecretArn is null)
            environment.Add(
                (
                    $"ConnectionStrings__{file.ConnectionStrings.Trax}",
                    Sub(
                        $"Host=${{DatabaseAddress}};Port=${{DatabasePort}};Database={DatabaseName};"
                            + $"Username={DatabaseUser};SSL Mode=VerifyFull;Root Certificate={RdsCaBundle};"
                            + "GSS Encryption Mode=Disable"
                    )
                )
            );
        foreach (var (name, value) in env.Settings)
            environment.Add((name, value));
        if (env.Auth is { Kind: DeployAuth.Cognito } auth)
        {
            environment.Add(
                (
                    auth.AuthorityKey,
                    Sub("https://cognito-idp.${AWS::Region}.amazonaws.com/${UserPoolId}")
                )
            );
            environment.Add((auth.AudienceKey, Ref("UserPoolClientId")));
        }
        return environment;
    }

    private static List<(string Name, JsonNode From)> TaskSecrets(
        DeployFile file,
        DeployEnvironment env,
        string stack
    )
    {
        var secrets = new List<(string Name, JsonNode From)>();
        if (env.DatabaseSecretArn is { } byo)
            secrets.Add(($"ConnectionStrings__{file.ConnectionStrings.Trax}", byo));
        else
            secrets.Add(("PGPASSWORD", Sub("${DatabaseSecretArn}:password::")));
        foreach (var name in file.Secrets)
            secrets.Add((name, AppSecretName(stack, name)));
        return secrets;
    }

    private static void AddServices(
        JsonObject resources,
        JsonObject outputs,
        DeployFile file,
        string stack,
        string? api,
        List<(string Name, JsonNode Value)> environment,
        List<(string Name, JsonNode From)> secrets,
        ServiceNetwork network,
        bool production
    )
    {
        var serving = environment.Append((TraxMigrate.Variable, TraxMigrate.SkipValue)).ToList();
        foreach (var service in file.Services.Keys)
            AddService(
                resources,
                outputs,
                service,
                stack,
                api,
                serving,
                secrets,
                network,
                production
            );
    }

    private static void AddService(
        JsonObject resources,
        JsonObject outputs,
        string service,
        string stack,
        string? api,
        List<(string Name, JsonNode Value)> serving,
        List<(string Name, JsonNode From)> secrets,
        ServiceNetwork network,
        bool production
    )
    {
        var isApi = string.Equals(service, api, StringComparison.Ordinal);
        AddTask(
            resources,
            stack,
            service,
            Ref(ImageParameter(service)),
            serving,
            secrets,
            port: isApi,
            command: null
        );
        var id = LogicalId(service);
        var properties = ServiceProperties(service, id, network);
        var resource = Resource("AWS::ECS::Service", properties);
        if (isApi)
        {
            properties["LoadBalancers"] = new JsonArray(
                new JsonObject
                {
                    ["ContainerName"] = service,
                    ["ContainerPort"] = ContainerPort,
                    ["TargetGroupArn"] = Ref("TargetGroup"),
                }
            );
            properties["HealthCheckGracePeriodSeconds"] = 120;
            resource["DependsOn"] = production
                ? new JsonArray("HttpsListener", "HttpListener")
                : new JsonArray("HttpListener");
        }
        resources[$"{id}Service"] = resource;
        outputs[ServiceOutput(service)] = Output(GetAtt($"{id}Service", "Name"));
    }

    private static JsonObject ServiceProperties(
        string service,
        string id,
        ServiceNetwork network
    ) =>
        new JsonObject
        {
            ["ServiceName"] = service,
            ["Cluster"] = Ref("Cluster"),
            ["LaunchType"] = "FARGATE",
            ["TaskDefinition"] = Ref($"{id}TaskDefinition"),
            ["DesiredCount"] = Ref(CountParameter(service)),
            ["DeploymentConfiguration"] = new JsonObject
            {
                // The new copy is healthy before the old one stops, and a version that never gets healthy is
                // rolled back.
                ["MinimumHealthyPercent"] = 100,
                ["MaximumPercent"] = 200,
                ["DeploymentCircuitBreaker"] = new JsonObject
                {
                    ["Enable"] = true,
                    ["Rollback"] = true,
                },
            },
            ["NetworkConfiguration"] = new JsonObject
            {
                ["AwsvpcConfiguration"] = new JsonObject
                {
                    ["Subnets"] = network.Subnets.DeepClone(),
                    ["SecurityGroups"] = network.SecurityGroups.DeepClone(),
                    ["AssignPublicIp"] = network.AssignPublicIp,
                },
            },
            ["EnableExecuteCommand"] = false,
            ["PropagateTags"] = "SERVICE",
        };

    private static JsonObject Template(
        string description,
        JsonObject parameters,
        JsonObject resources,
        JsonObject outputs
    )
    {
        var template = new JsonObject
        {
            ["AWSTemplateFormatVersion"] = "2010-09-09",
            ["Description"] = description,
        };
        if (parameters.Count > 0)
            template["Parameters"] = parameters;
        // Without a Protect or user pool parameter there is no condition, and so no Conditions section.
        if (Conditions(parameters) is { Count: > 0 } conditions)
            template["Conditions"] = conditions;
        template["Resources"] = resources;
        template["Outputs"] = outputs;
        return template;
    }

    /// <summary>The template as CloudFormation receives it: compact, so it fits the 51,200-byte inline limit.</summary>
    public static string Compact(JsonObject template) => template.ToJsonString();

    /// <summary>The template as <c>trax deploy plan</c> writes it, for reading and diffing.</summary>
    public static string Indented(JsonObject template) =>
        template.ToJsonString(
            new JsonSerializerOptions
            {
                WriteIndented = true,
                RespectNullableAnnotations = false,
                RespectRequiredConstructorParameters = false,
            }
        ) + "\n";

    /// <summary>Refuses what this stack cannot give the hosts.</summary>
    internal static void Check(
        DeployFile file,
        DeployEnvironment env,
        IReadOnlyDictionary<string, DeployManifest> exports
    )
    {
        ComposeTarget.CheckHosts(file, exports, name => file.Count(env, name));
        var apis = file.Services.Keys.Where(s => exports[s].Roles.Contains("api")).ToList();
        if (apis.Count > 1)
            throw new InvalidOperationException(
                $"Services {string.Join(" and ", apis)} both serve the Trax API, and a stack routes one load "
                    + "balancer to one service. Deploy one API service per app."
            );
        if (apis is [var api] && exports[api].Endpoints.Health is null)
            throw new InvalidOperationException(
                $"Service '{api}' maps no health check, which the load balancer needs to know a copy is ready. "
                    + "Add builder.Services.AddHealthChecks().AddTraxHealthCheck() and "
                    + "app.MapHealthChecks(\"/trax/health\")."
            );
        var rabbit = file
            .Services.Keys.Where(s => exports[s].Transports.Contains("rabbitmq"))
            .ToList();
        if (rabbit.Count > 0)
            throw new InvalidOperationException(
                $"Service '{rabbit[0]}' connects to RabbitMQ, which an AWS stack does not provide yet. Deploy "
                    + "with --target compose, or broadcast without RabbitMQ."
            );
        if (env.Auth is { Kind: DeployAuth.Cognito } && apis.Count == 0)
            throw new InvalidOperationException(
                "auth is cognito, and no service serves the Trax API to sign in to."
            );
    }

