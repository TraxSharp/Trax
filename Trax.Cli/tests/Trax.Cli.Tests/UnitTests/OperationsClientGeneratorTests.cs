    private static (string Schema, List<ClientDocumentFile> Documents) ConsoleSources()
    {
        for (
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            dir is not null;
            dir = dir.Parent
        )
        {
            var app = Path.Combine(
                dir.FullName,
                "Trax.Api",
                "src",
                "Trax.Api.Dashboard",
                "ClientApp"
