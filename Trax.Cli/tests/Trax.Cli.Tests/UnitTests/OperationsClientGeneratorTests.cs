using System.Text.Json;
using AwesomeAssertions;
using Trax.Cli.Clients;
using Trax.Cli.Commands;

namespace Trax.Cli.Tests.UnitTests;

/// <summary>
/// <c>trax client --operations</c> reads the operations console's <c>.graphql</c> files against the operations
/// schema, refuses one a host would not register as a console document (a root other than <c>operations</c>, a
/// stream other than the operator's, an alias at the root, a directive) or one the schema does not serve, types each
/// operation's variables and result, names each by the id a host registers it under, and writes the
/// <c>console-documents.json</c> a host registers them from. It never reads or writes a host's client manifest.
/// <para>Enforces <c>Trax.Docs/adr/0057-the-operations-console-sends-only-documents-trax-client-generated.md</c>.</para>
/// </summary>
[Property(
    "adr",
    "Trax.Docs/adr/0057-the-operations-console-sends-only-documents-trax-client-generated.md"
)]
public class OperationsClientGeneratorTests
{
    private const string Adr =
        "Trax.Docs/adr/0057-the-operations-console-sends-only-documents-trax-client-generated.md";

    private const string Schema = """
        schema {
          query: RootQuery
          mutation: RootMutation
          subscription: Streams
        }

        scalar Long

        type RootQuery {
          operations: OperationsQueries
          persistedOperations: PersistedQueries
          discover: Discover
        }

        type RootMutation {
          operations: OperationsMutations
        }

        type Streams {
          onDataChanged: DataChanged!
          onSomethingElse: DataChanged!
        }

        "What the operator reads."
        type OperationsQueries {
          runs(state: RunState, take: Int! = 25): [Run!]!
          run(id: Long!): Run
        }

        type OperationsMutations {
          cancel(id: Long!, note: String): CancelResponse!
        }

        type PersistedQueries {
          count: Int!
        }

        type Discover {
          secret: String
        }

        type CancelResponse {
          success: Boolean!
          message: String
        }

        type DataChanged {
          domain: Domain!
        }

        type Run {
          id: Long!
          state: RunState!
          name: String
        }

        enum RunState {
          RUNNING
          FAILED
        }

        enum Domain {
          RUN
          QUEUE
        }
        """;

    private const string Runs = """
        # Runs, newest first.
        query Runs($state: RunState, $take: Int) {
          operations {
            runs(state: $state, take: $take) {
              id
              state
              name
            }
          }
        }
        """;

    #region What it writes

    [Test]
    public void A_query_is_typed_from_the_schema_and_named_by_the_id_a_host_registers()
    {
        var files = Render(("src/graphql/Runs.graphql", Runs));
        var module = Text(files, "documents/runs.g.ts");
        var text = Documents(files)[0].GetProperty("text").GetString()!;

        module
            .Should()
            .StartWith("// Generated by trax client from the operations schema. Do not edit.\n")
            .And.Contain(
                "export interface RunsVariables {\n  state?: RunState | null;\n  take?: number | null;\n}"
            )
            .And.Contain("export type RunsResult = {\n  operations: {")
            .And.Contain(
                "runs: Array<{\n      id: number;\n      state: RunState;\n      name: string | null;"
            )
            .And.Contain("} | null;\n};")
            .And.Contain("kind: \"query\",")
            .And.Contain(
                $"id: \"{ClientDocumentSet.ConsoleIdOf("Runs", text)}\",",
                "the console sends the id a host gives the text it registers, per " + Adr
            )
            .And.Contain(
                "export function runs(variables: RunsVariables = {}): Promise<RunsResult> {\n  return send(runsDocument, variables);"
            );
        text.Should()
            .NotContain("#", "the document's comments stay in its file and are never sent");
        Text(files, "types.g.ts")
            .Should()
            .Contain("export type RunState = \"RUNNING\" | \"FAILED\";");
        Text(files, "index.g.ts")
            .Should()
            .Contain(
                "export { runs, runsDocument, type RunsVariables, type RunsResult } from \"./documents/runs.g\";"
            );
    }

    [Test]
    public void A_nullable_variable_may_feed_an_argument_that_has_a_default()
    {
        // take: Int! = 25 takes $take: Int, as GraphQL allows; the host would run it.
        var act = () => Render(("src/graphql/Runs.graphql", Runs));

        act.Should().NotThrow();
    }

    [Test]
    public void A_mutation_with_a_required_variable_takes_its_variables()
    {
        var module = Text(
            Render(
                (
                    "src/graphql/Cancel.graphql",
                    "mutation Cancel($id: Long!, $note: String) { operations { cancel(id: $id, note: $note) { success message } } }"
                )
            ),
            "documents/cancel.g.ts"
        );

        module
            .Should()
            .Contain("kind: \"mutation\",")
            .And.Contain(
                "export interface CancelVariables {\n  id: number;\n  note?: string | null;\n}"
            )
            .And.Contain(
                "export function cancel(variables: CancelVariables): Promise<CancelResult> {"
            );
    }

    [Test]
    public void A_subscription_to_an_operator_stream_is_followed_through_a_sink()
    {
        var module = Text(
            Render(
                (
                    "src/graphql/OnDataChanged.graphql",
                    "subscription OnDataChanged { onDataChanged { domain } }"
                )
            ),
            "documents/onDataChanged.g.ts"
        );

        module
            .Should()
            .Contain("kind: \"subscription\",")
            .And.Contain("export type OnDataChangedVariables = Record<string, never>;")
            .And.Contain(
                "export function onDataChanged(sink: TraxSink<OnDataChangedResult>): () => void {\n  return subscribe(onDataChangedDocument, {}, sink);"
            );
    }

    [Test]
    public void Persisted_operation_management_has_no_id_and_is_left_out_of_the_registered_documents()
    {
        var files = Render(
            ("src/graphql/Runs.graphql", Runs),
            ("src/graphql/Count.graphql", "query Count { persistedOperations { count } }")
        );

        Text(files, "documents/count.g.ts")
            .Should()
            .Contain(
                "id: null,",
                "a host runs persisted-operation management as text, behind its own gate"
            );
        Documents(files)
            .Select(d => d.GetProperty("name").GetString())
            .Should()
            .Equal(
                ["Runs"],
                "a host registers only the console's operations documents, per " + Adr
            );
    }

    [Test]
    public void The_registered_documents_file_is_the_one_a_host_embeds()
    {
        var file = Text(Render(("src/graphql/Runs.graphql", Runs)), "console-documents.json");

        using var json = JsonDocument.Parse(file);
        json.RootElement.GetProperty("format").GetInt32().Should().Be(1);
        json.RootElement.GetProperty("documents")[0]
            .EnumerateObject()
            .Select(p => p.Name)
            .Should()
            .Equal("name", "text");
        file.Should().EndWith("}\n");
    }

    [Test]
    public void The_cli_and_the_host_name_a_console_document_alike()
    {
        var cases = FixtureCases();
        cases.Should().NotBeEmpty();
        foreach (var (name, text, id) in cases)
            ClientDocumentSet
                .ConsoleIdOf(name, text)
                .Should()
                .Be(id, "the host registers the text under this id, per " + Adr);
    }

    #endregion

    #region What it refuses

    [TestCase(
        "query Peek { discover { secret } }",
        "'Peek' selects something other than 'operations', or 'persistedOperations' alone, at its root."
    )]
    [TestCase(
        "query Both { operations { run(id: 1) { id } } persistedOperations { count } }",
        "'Both' selects something other than 'operations', or 'persistedOperations' alone, at its root."
    )]
    [TestCase(
        "query Aliased { ops: operations { run(id: 1) { id } } }",
        "'Aliased' selects something other than a field, or an alias, at its root."
    )]
    [TestCase(
        "subscription Other { onSomethingElse { domain } }",
        "'Other' subscribes to something other than one of the operator's streams"
    )]
    [TestCase(
        "query Skipped($s: Boolean!) { operations @skip(if: $s) { run(id: 1) { id } } }",
        "'Skipped' uses a directive; a console document uses none."
    )]
    [TestCase("query Missing { operations { gone } }", "OperationsQueries has no field 'gone'.")]
    [TestCase(
        "query Unused($id: Long!) { operations { run(id: 1) { id } } }",
        "'Unused' declares the variable '$id' and never uses it."
    )]
    public void A_document_a_host_would_not_register_is_refused_naming_its_file(
        string document,
        string reason
    )
    {
        var act = () => Render(("src/graphql/Doc.graphql", document));

        act.Should()
            .Throw<InvalidOperationException>()
            .WithMessage($"*src/graphql/Doc.graphql:*{reason}*");
    }

    [Test]
    public void A_schema_that_is_not_sdl_is_refused()
    {
        var act = () =>
            ClientGenerator.Render(
                new OperationsGenerateOptions(
                    "type {",
                    [new ClientDocumentFile("src/graphql/Runs.graphql", Runs)]
                )
            );

        act.Should()
            .Throw<InvalidOperationException>()
            .WithMessage("The operations schema is not GraphQL SDL*");
    }

    #endregion

    #region On disk

    [Test]
    public void Check_passes_on_what_write_wrote_and_names_a_document_that_changed()
    {
        var dir = Directory.CreateTempSubdirectory("trax-operations-client-").FullName;
        try
        {
            var options = Options(("src/graphql/Runs.graphql", Runs));
            ClientGenerator.Write(options, dir);

            ClientGenerator.Check(options, dir).Should().BeEmpty();
            ClientGenerator
                .Check(Options(("src/graphql/Runs.graphql", Runs.Replace("name\n", ""))), dir)
                .Select(d => d.Path)
                .Should()
                .Contain(["console-documents.json", "documents/runs.g.ts"]);
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    [Test]
    public void Write_removes_the_module_of_a_document_that_is_gone()
    {
        var dir = Directory.CreateTempSubdirectory("trax-operations-client-").FullName;
        try
        {
            ClientGenerator.Write(
                Options(
                    ("src/graphql/Runs.graphql", Runs),
                    ("src/graphql/Count.graphql", "query Count { persistedOperations { count } }")
                ),
                dir
            );
            File.WriteAllText(
                Path.Combine(dir, "documents", "mine.g.ts"),
                "// an app's own file\n"
            );

            ClientGenerator.Write(Options(("src/graphql/Runs.graphql", Runs)), dir);

            File.Exists(Path.Combine(dir, "documents", "count.g.ts")).Should().BeFalse();
            File.Exists(Path.Combine(dir, "documents", "mine.g.ts"))
                .Should()
                .BeTrue("only a file this generator wrote is removed");
        }
        finally
        {
            Directory.Delete(dir, recursive: true);
        }
    }

    [Test]
    public void The_command_refuses_a_manifest_beside_the_operations_schema_and_needs_documents()
    {
        var error = new StringWriter();
        var previous = Console.Error;
        Console.SetError(error);
        try
        {
            ClientCommand
                .RunOperations("manifest.json", "operations.graphql", "out", false, ["*.graphql"])
                .Should()
                .Be(1);
            ClientCommand
                .RunOperations(null, "operations.graphql", "out", false, [])
                .Should()
                .Be(1);
        }
        finally
        {
            Console.SetError(previous);
        }

        error
            .ToString()
            .Should()
            .Contain("leave out --manifest")
            .And.Contain("name them with --documents");
    }

    #endregion

    private static OperationsGenerateOptions Options(
        params (string Source, string Text)[] documents
    ) => new(Schema, documents.Select(d => new ClientDocumentFile(d.Source, d.Text)).ToList());

    private static IReadOnlyList<ClientFile> Render(
        params (string Source, string Text)[] documents
    ) => ClientGenerator.Render(Options(documents));

    private static string Text(IReadOnlyList<ClientFile> files, string path) =>
        files.Single(f => f.Path == path).Text;

    private static List<JsonElement> Documents(IReadOnlyList<ClientFile> files)
    {
        using var json = JsonDocument.Parse(Text(files, "console-documents.json"));
        return json
            .RootElement.GetProperty("documents")
            .EnumerateArray()
            .Select(e => e.Clone())
            .ToList();
    }

    // The cases both this suite and the host's read, from the source tree above the test's directory.
    private static List<(string Name, string Text, string Id)> FixtureCases()
    {
        for (
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            dir is not null;
            dir = dir.Parent
        )
        {
            var candidate = Path.Combine(
                dir.FullName,
                "Trax.Api",
                "tests",
                "Trax.Api.Tests",
                "PersistedOperations",
                "Fixtures",
                "console-document-ids.json"
            );
            if (!File.Exists(candidate))
                continue;
            using var json = JsonDocument.Parse(File.ReadAllText(candidate));
            return json
                .RootElement.GetProperty("cases")
                .EnumerateArray()
                .Select(c =>
                    (
                        c.GetProperty("name").GetString()!,
                        c.GetProperty("text").GetString()!,
                        c.GetProperty("id").GetString()!
                    )
                )
                .ToList();
        }
        Assert.Ignore("Trax.Api's console-document-ids.json not found (isolated build).");
        return [];
    }
}
