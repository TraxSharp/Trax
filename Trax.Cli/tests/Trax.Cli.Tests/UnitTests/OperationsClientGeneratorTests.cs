    // Compiles a C# client against Trax.Client and everything deployed with the tests, and loads it when it builds.
    private static IEnumerable<Microsoft.CodeAnalysis.Diagnostic> CompileCSharp(
        IReadOnlyList<ClientFile> files,
        out System.Reflection.Assembly? assembly,
        params string[] callers
    )
    {
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Select(path => Microsoft.CodeAnalysis.MetadataReference.CreateFromFile(path));
        var compilation = Microsoft.CodeAnalysis.CSharp.CSharpCompilation.Create(
            "OperationsClient" + Guid.NewGuid().ToString("N"),
            files
                .Select(f => (f.Text, f.Path))
                .Concat(callers.Select((text, i) => (text, $"Caller{i}.cs")))
                .Select(f =>
                    Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(
                        f.Item1,
                        Microsoft.CodeAnalysis.CSharp.CSharpParseOptions.Default.WithDocumentationMode(
                            Microsoft.CodeAnalysis.DocumentationMode.Diagnose
                        ),
                        path: f.Item2
                    )
                ),
            references,
            new Microsoft.CodeAnalysis.CSharp.CSharpCompilationOptions(
                Microsoft.CodeAnalysis.OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: Microsoft.CodeAnalysis.NullableContextOptions.Enable
            )
        );
        using var image = new MemoryStream();
        var emitted = compilation.Emit(image);
        assembly = emitted.Success ? System.Reflection.Assembly.Load(image.ToArray()) : null;
        return emitted.Diagnostics;
    }

    // The console's schema and documents, from the source tree above the test's directory.
    private static (string Schema, List<ClientDocumentFile> Documents) ConsoleSources()
    {
        for (
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            dir is not null;
            dir = dir.Parent
        )
        {
            var app = Path.Combine(
                dir.FullName,
                "Trax.Api",
                "src",
                "Trax.Api.Dashboard",
                "ClientApp"
            );
            if (!File.Exists(Path.Combine(app, "operations.graphql")))
                continue;
            var documents = Directory
                .EnumerateFiles(Path.Combine(app, "src", "graphql"), "*.graphql")
                .Order(StringComparer.Ordinal)
                .Select(path => new ClientDocumentFile(
                    "src/graphql/" + Path.GetFileName(path),
                    File.ReadAllText(path)
                ))
                .ToList();
            return (File.ReadAllText(Path.Combine(app, "operations.graphql")), documents);
        }
        if (Environment.GetEnvironmentVariable("CI") is not null)
            Assert.Fail("Trax.Api's operations console not found, and CI always checks it out.");
        Assert.Ignore("Trax.Api's operations console not found (isolated build).");
        return default;
    }

