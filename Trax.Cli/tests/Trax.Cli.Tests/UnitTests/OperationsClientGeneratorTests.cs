/// <summary>
/// <c>trax client --operations</c> reads the operations console's <c>.graphql</c> files against the operations
/// schema, refuses one a host would not register as a console document (a root other than <c>operations</c>, a
/// stream other than the operator's, an alias at the root, a directive) or one the schema does not serve, types each
/// operation's variables and result, names each by the id a host registers it under, and writes the
/// <c>console-documents.json</c> a host registers them from. It never reads or writes a host's client manifest.
/// <para>Enforces <c>Trax.Docs/adr/0057-the-operations-console-sends-only-documents-trax-client-generated.md</c>.</para>
/// </summary>
[Property(
    "adr",
    "Trax.Docs/adr/0057-the-operations-console-sends-only-documents-trax-client-generated.md"
)]
public class OperationsClientGeneratorTests
