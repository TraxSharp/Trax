#!/usr/bin/env bash
# Writes the profile the package ships, from rules.txt:
#   src/Trax.Analyzers.Package/configuration/<level>/src.globalconfig    for source projects
#   src/Trax.Analyzers.Package/configuration/<level>/tests.globalconfig  for test projects
# <level> is TraxAnalysisLevel: a release that changes what the profile reports adds a level, and a
# consumer who pins the old one keeps the old profile.
#
#   Trax.Analyzers/tools/generate-profile.sh           write
#   Trax.Analyzers/tools/generate-profile.sh --check   fail if the committed files differ (CI)
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
level=1
dir="$here/src/Trax.Analyzers.Package/configuration/$level"
check="${1:-}"

valid='^(error|warning|suggestion|silent|none)$'

write() {
  local column="$1" what="$2"
  echo "# Generated by Trax.Analyzers/tools/generate-profile.sh from rules.txt. Do not edit."
  echo "# The Trax.Analyzers profile, level $level, for $what."
  echo "is_global = true"
  # Below every configuration a consumer writes, so theirs wins.
  echo "global_level = -1"
  echo
  grep -v -E '^\s*(#|$)' "$here/rules.txt" | while read -r id src tests _; do
    case "$column" in src) sev="$src" ;; tests) sev="$tests" ;; esac
    [[ "$id" =~ ^(TRX|RS)[0-9]{4}$ ]] || { echo "rules.txt: bad id '$id'" >&2; exit 1; }
    [[ "$sev" =~ $valid ]] || { echo "rules.txt: $id has severity '$sev'" >&2; exit 1; }
    echo "dotnet_diagnostic.$id.severity = $sev"
  done
}

ids="$(grep -v -E '^\s*(#|$)' "$here/rules.txt" | awk '{print $1}')"
dupes="$(sort <<<"$ids" | uniq -d)"
[ -z "$dupes" ] || { echo "rules.txt lists these twice: $dupes" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
write src "source projects" > "$tmp/src.globalconfig"
write tests "test projects" > "$tmp/tests.globalconfig"

if [ "$check" = "--check" ]; then
  diff -u "$dir/src.globalconfig" "$tmp/src.globalconfig" &&
    diff -u "$dir/tests.globalconfig" "$tmp/tests.globalconfig" ||
    { echo "The profile is out of date: run Trax.Analyzers/tools/generate-profile.sh" >&2; exit 1; }
  echo "Profile matches rules.txt"
else
  mkdir -p "$dir"
  cp "$tmp/src.globalconfig" "$tmp/tests.globalconfig" "$dir/"
  echo "Wrote $dir"
fi
