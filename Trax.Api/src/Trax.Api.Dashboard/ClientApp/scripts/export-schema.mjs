// Introspects the running devhost and writes the SDL to src/mock/schema-sdl.ts.
// The mock layer builds its auto-mock schema from this string, so it must be
// refreshed whenever the Trax GraphQL schema changes.
//
//   npm run mock:schema            # needs the devhost running on :5310
//   TRAX_API_URL=... TRAX_API_KEY=... node scripts/export-schema.mjs
//
// Any host that serves the operations view does, with an operator's key: a sample host such as
// Trax.Samples' Recovery (it registers state machines, so onMachineInstanceChanged is in it), run with
// Recovery__RequirePersistedOperations=false so it answers introspection. The snapshot keeps only what
// the console reads (see consoleSurface), so it does not depend on which host it was read from.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { GraphQLObjectType, GraphQLSchema, buildClientSchema, getIntrospectionQuery, printSchema } from "graphql";

const URL = process.env.TRAX_API_URL ?? "http://localhost:5310/trax/graphql";
const KEY = process.env.TRAX_API_KEY ?? "admin-key-do-not-use-in-production";
const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../src/mock/schema-sdl.ts");

const res = await fetch(URL, {
  method: "POST",
  headers: { "Content-Type": "application/json", "X-Api-Key": KEY },
  body: JSON.stringify({ query: getIntrospectionQuery() }),
});

if (!res.ok) {
  console.error(`Introspection request failed: HTTP ${res.status}`);
  process.exit(1);
}

const json = await res.json();
if (json.errors) {
  console.error("Introspection returned errors:", JSON.stringify(json.errors, null, 2));
  process.exit(1);
}

// HotChocolate 16 adds its own types under the reserved "__" prefix (__SearchResult,
// __SchemaDefinition). graphql-js refuses to validate a schema containing them, so the mock
// could never execute against it; drop everything "__" that is not standard introspection.
const STANDARD = new Set(["__Schema", "__Type", "__TypeKind", "__Field", "__InputValue", "__EnumValue", "__Directive", "__DirectiveLocation"]);
json.data.__schema.types = json.data.__schema.types.filter(
  (t) => !t.name.startsWith("__") || STANDARD.has(t.name),
);
/**
 * The schema the console talks to: operations and persistedOperations, and Trax's own feeds (the on*
 * subscriptions). What a host's own trains and machines add (dispatch, discover, machines, runProgress,
 * a machine's <name>Changed feed) is left out, with every type only it reaches.
 */
function consoleSurface(full) {
  const only = (type, wanted) => {
    if (!type) return undefined;
    const config = type.toConfig();
    return new GraphQLObjectType({
      ...config,
      fields: Object.fromEntries(Object.entries(config.fields).filter(([name]) => wanted(name))),
    });
  };
  const ours = (name) => name === "operations" || name === "persistedOperations";
  const roots = {
    query: only(full.getQueryType(), ours),
    mutation: only(full.getMutationType(), ours),
    subscription: only(full.getSubscriptionType(), (name) => /^on[A-Z]/.test(name)),
  };
  // The types these roots reach, printed in the order the host listed them.
  const reached = new GraphQLSchema({ ...full.toConfig(), ...roots, types: [] }).getTypeMap();
  const rootNames = new Set(Object.values(roots).filter(Boolean).map((t) => t.name));
  const types = full.toConfig().types.filter((t) => t.name in reached && !rootNames.has(t.name));
  return new GraphQLSchema({ ...full.toConfig(), ...roots, types });
}

const sdl = printSchema(consoleSurface(buildClientSchema(json.data)));
const header =
  "// GENERATED by scripts/export-schema.mjs — do not edit by hand.\n" +
  "// Regenerate with `npm run mock:schema` while the devhost is running.\n";
writeFileSync(OUT, `${header}export const SCHEMA_SDL = ${JSON.stringify(sdl)};\n`);
console.log(`Wrote ${sdl.length} chars of SDL to src/mock/schema-sdl.ts`);
