using System.Text;
using System.Text.Json.Nodes;
using AwesomeAssertions;
using Trax.Effect.StateMachine.Tests.Fakes;
using Trax.Effect.StateMachine.Tests.Helpers;

namespace Trax.Effect.StateMachine.Tests.Conformance;

/// <summary>
/// <see cref="StrictInputMachine.Cases"/>, written as data any engine replays: the machine's IR and, for each value,
/// the input it sends and the C# engine's answer. The verdicts are the CLR's (<see cref="StrictInputParityTests"/>
/// holds the engine to them), so an engine in another language that replays <c>conformance/strict-input/</c> checks
/// its format, enum and range rules against the CLR without running .NET or node. Regenerate both files deliberately
/// with <c>UPDATE_CONFORMANCE=1</c>.
/// </summary>
public class StrictInputGoldenTests
{
    private static string Dir => Path.Combine(FixturePaths.ConformanceRoot, "strict-input");

    private static string IrFile => Path.Combine(Dir, "strict.ir.json");

    private static string CasesFile => Path.Combine(Dir, "cases.json");

    [Test]
    public void The_committed_IR_is_what_the_exporter_writes()
    {
        var exported = IrExporter.Export(StrictInputMachine.Built) + "\n";
        Update(IrFile, exported);

        File.ReadAllText(IrFile)
            .Should()
            .Be(exported, "regenerate it deliberately with UPDATE_CONFORMANCE=1");
    }

    [Test]
    public void The_committed_cases_are_what_the_engine_answers()
    {
        var written = Write();
        Update(CasesFile, written);

        File.ReadAllText(CasesFile)
            .Should()
            .Be(written, "regenerate it deliberately with UPDATE_CONFORMANCE=1");
    }

    [Test]
    public void Replaying_the_committed_file_gives_its_answers()
    {
        // The file stores numbers as the canonical wire writes them (3.4028235e+38, not 3.4028235E+38), so it is
        // replayed as read, not trusted to mean what the C# literals did.
        var golden = (JsonObject)JsonNode.Parse(File.ReadAllText(CasesFile))!;
        var start = StrictInputMachine.Machine.Rehydrate(golden["start"]!.GetValue<string>());
        var snapshot = start.Should().BeOfType<RehydrationResult.Ok>().Which.Snapshot;
        var trigger = golden["trigger"]!.GetValue<string>();

        var diffs = new List<string>();
        foreach (var node in golden["cases"]!.AsArray())
        {
            var @case = (JsonObject)node!;
            var input = (JsonObject)golden["validInput"]!.DeepClone();
            if (@case["field"] is { } field)
                input[field.GetValue<string>()] = @case["value"]?.DeepClone();
            var expect = Answer(StrictInputMachine.Machine.Advance(snapshot, trigger, input));
            if (expect.ToJsonString() != @case["expect"]!.ToJsonString())
                diffs.Add(
                    $"{@case["name"]}: file says {@case["expect"]!.ToJsonString()}, engine {expect.ToJsonString()}"
                );
        }

        diffs.Should().BeEmpty(string.Join("\n", diffs));
    }

    private static string Write()
    {
        var start = StrictInputMachine.Open();
        var trigger = nameof(StrictTrigger.Submit);
        var valid = StrictInputMachine.ValidInput();

        // One case per line, each line canonical JSON, so a changed verdict is a one-line diff.
        var lines = StrictInputMachine
            .Cases.Select(c =>
                CanonicalJson.Serialize(
                    new JsonObject
                    {
                        ["name"] = c.Name,
                        ["field"] = c.Field,
                        ["value"] = c.Value?.DeepClone(),
                        ["expect"] = Answer(
                            StrictInputMachine.Machine.Advance(start, trigger, c.Input())
                        ),
                    }
                )
            )
            .Prepend(
                CanonicalJson.Serialize(
                    new JsonObject
                    {
                        ["name"] = "valid input",
                        ["expect"] = Answer(
                            StrictInputMachine.Machine.Advance(start, trigger, valid.DeepClone())
                        ),
                    }
                )
            );

        var sb = new StringBuilder();
        sb.Append("{\n");
        sb.Append(
            "  \"_comment\": \"GENERATED by StrictInputGoldenTests from StrictInputMachine.Cases (Trax.Effect tests). "
                + "Each case advances 'start' on 'trigger' through the machine in strict.ir.json, with 'validInput' "
                + "whose member 'field' is set to 'value' (a case with no 'field' sends 'validInput' as is). 'expect' is "
                + "the C# engine's answer, which is the CLR type's verdict. Regenerate with UPDATE_CONFORMANCE=1.\",\n"
        );
        sb.Append("  \"machine\": \"strict\",\n");
        sb.Append("  \"start\": ")
            .Append(CanonicalJson.Serialize(StrictInputMachine.Machine.Serialize(start)))
            .Append(",\n");
        sb.Append("  \"trigger\": ").Append(CanonicalJson.Serialize(trigger)).Append(",\n");
        sb.Append("  \"validInput\": ").Append(CanonicalJson.Serialize(valid)).Append(",\n");
        sb.Append("  \"cases\": [\n    ");
        sb.Append(string.Join(",\n    ", lines));
        sb.Append("\n  ]\n}\n");
        return sb.ToString();
    }

    private static JsonObject Answer(AdvanceResult result) =>
        result switch
        {
            AdvanceResult.Transitioned t => new JsonObject
            {
                ["outcome"] = "transitioned",
                ["wire"] = StrictInputMachine.Machine.Serialize(t.Snapshot),
            },
            AdvanceResult.Rejected r => new JsonObject
            {
                ["outcome"] = "rejected",
                ["reason"] = r.Reason.ToWire(),
            },
            _ => throw new InvalidOperationException($"Unexpected advance result {result}."),
        };

    private static void Update(string path, string content)
    {
        if (Environment.GetEnvironmentVariable("UPDATE_CONFORMANCE") != "1")
            return;
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }
}
