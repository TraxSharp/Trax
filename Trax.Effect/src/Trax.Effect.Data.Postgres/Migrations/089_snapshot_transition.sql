-- A state-machine instance's history (Trax.Effect.StateMachine.Persistence, effect/0022): one row for every
-- snapshot the store writes, in the same transaction as the write. The model is
-- Trax.Effect.Models.SnapshotTransition, on IDataContext.SnapshotTransitions. A row holds names and times, never
-- the instance's context or its owner's key.
--
-- id: the row's identity.
-- draft_row_id: the instance's row. row_id names one incarnation (076), so a draft deleted and created again under
--   the same id starts a history of its own. The history goes with its row: an AFTER DELETE trigger on
--   snapshot_draft deletes it, so every existing delete of an instance (a discard, the expiry sweep, host code)
--   keeps working without knowing this table exists. uq_snapshot_transition_draft_revision leads with it, so that
--   index serves the trigger's delete and the newest-first read of one instance's history.
--
--   A trigger rather than a foreign key: a foreign key would depend on pk_snapshot_draft, and 051, which every
--   script from 046 on must survive running again (effect/0014), drops and rebuilds that key.
-- revision: the revision the write gave the row (076). One row per revision; a write that leaves the snapshot
--   alone, or a writer that goes around the store, writes none, so revisions can skip.
-- kind: what wrote it: start, command, save, timer or outcome.
-- trigger: the command that moved it (an event, a timer's event, or State.done / State.failed / State.cancelled
--   for a run's outcome), or null for a creation, a save, or an outcome that could not be applied.
-- actor: who made it: the owner (a client acting for a user's instance), host code driving a system instance, or
--   the machine itself (a timer, an outcome, a spawn). A kind of actor, never a user.
-- from_state: the state it left, null for a creation. to_state: the state it entered.
-- occurred_at: the row's updated_at from the same write.
-- invoke_token: what the write started, or null: the external id of the run entering its state queued, or the
--   token of the child it spawned. Server-only.
--
-- The table is new, so nothing here scans or locks a populated table (effect/0014).
--
-- Every statement checks before it changes anything, so the script can run again over its own result.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'snapshot_transition_kind' AND n.nspname = 'trax'
    ) THEN
        CREATE TYPE trax.snapshot_transition_kind AS ENUM ('start', 'command', 'save', 'timer', 'outcome');
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'snapshot_transition_actor' AND n.nspname = 'trax'
    ) THEN
        CREATE TYPE trax.snapshot_transition_actor AS ENUM ('owner', 'host', 'machine');
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS trax.snapshot_transition (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_snapshot_transition PRIMARY KEY,
    draft_row_id bigint NOT NULL,
    revision bigint NOT NULL,
    kind trax.snapshot_transition_kind NOT NULL,
    trigger text NULL,
    actor trax.snapshot_transition_actor NOT NULL,
    from_state text NULL,
    to_state text NOT NULL,
    occurred_at timestamptz NOT NULL,
    invoke_token text NULL,
    CONSTRAINT uq_snapshot_transition_draft_revision UNIQUE (draft_row_id, revision)
);

-- One statement per delete, however many rows it deletes: the sweep's bulk delete removes every history it ends in
-- one more statement.
CREATE OR REPLACE FUNCTION trax.snapshot_draft_delete_history() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM trax.snapshot_transition t
    USING deleted_drafts d
    WHERE t.draft_row_id = d.row_id;
    RETURN NULL;
END
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'snapshot_draft_history'
          AND tgrelid = 'trax.snapshot_draft'::regclass
    ) THEN
        CREATE TRIGGER snapshot_draft_history
            AFTER DELETE ON trax.snapshot_draft
            REFERENCING OLD TABLE AS deleted_drafts
            FOR EACH STATEMENT
            EXECUTE FUNCTION trax.snapshot_draft_delete_history();
    END IF;
END$$;
