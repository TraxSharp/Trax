-- The fires machine policies still owe (Trax.StateMachine.Persistence, central 0058): a policy reacts to one
-- instance's transition by firing a server-only trigger on another. The row is written in the same transaction as the
-- transition, so it exists only if the transition committed, and it is deleted in the transaction that fires it, so a
-- fire happens once whichever host claims it and whenever: a host that was down fires what it owes when it starts. The
-- model is Trax.Effect.Models.MachinePolicyFire, on IDataContext.MachinePolicyFires. A row holds rows, ids and names,
-- never a context or an owner's key.
--
-- id: the row's identity.
-- policy: the policy, by the identity its host file gives it.
-- source_row_id, source_instance_id, source_revision: the instance whose transition set it off, and the revision that
--   transition gave its row. The owner is read from the source row when the row is fired, so it is not kept here.
-- target_row_id: the instance to fire, once a broadcast is expanded into one row per target; null until then, and for
--   a policy whose single target is found when it is fired.
-- created_at: when the row was written.
--
-- No foreign key to snapshot_draft: a row whose source or target is gone is dropped when it is fired, and a key would
-- depend on pk_snapshot_draft, which 051 drops and rebuilds when it runs again (effect/0014).
--
-- snapshot_transition_actor gains 'policy': a transition a policy made is the server's, never a user's.
--
-- The table is new, so nothing here scans or locks a populated table (effect/0014). Every statement checks before it
-- changes anything, so the script can run again over its own result.
ALTER TYPE trax.snapshot_transition_actor ADD VALUE IF NOT EXISTS 'policy';

CREATE TABLE IF NOT EXISTS trax.machine_policy_fire (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_machine_policy_fire PRIMARY KEY,
    policy text NOT NULL,
    source_row_id bigint NOT NULL,
    source_instance_id uuid NOT NULL,
    source_revision bigint NOT NULL,
    target_row_id bigint NULL,
    created_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_machine_policy_fire_policy ON trax.machine_policy_fire (policy, id);
