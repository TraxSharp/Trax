import { afterEach, describe, expect, it, vi } from 'vitest';

// The engine's version is fixed when the module is evaluated, from the constant the build defines. Each case
// defines it on the global, as the build would inline it, and loads a fresh copy of the module.
async function engineAt(version: string | undefined) {
  vi.resetModules();
  if (version === undefined) vi.unstubAllGlobals();
  else vi.stubGlobal('__TRAX_ENGINE_VERSION__', version);
  return import('./version');
}

describe('requireEngineVersion', () => {
  afterEach(() => {
    vi.unstubAllGlobals();
    vi.resetModules();
  });

  it('reports the version the build defined', async () => {
    expect((await engineAt('1.63.0')).engineVersion).toBe('1.63.0');
  });

  it('reports 0.0.0 when run from source', async () => {
    expect((await engineAt(undefined)).engineVersion).toBe('0.0.0');
  });

  it('accepts a twin generated for this version', async () => {
    const { requireEngineVersion } = await engineAt('1.63.0');
    expect(() => requireEngineVersion('1.63.0')).not.toThrow();
  });

  it('refuses a twin generated for another version, saying what to do', async () => {
    const { requireEngineVersion } = await engineAt('1.64.0');
    expect(() => requireEngineVersion('1.63.0')).toThrow(
      /generated by trax 1\.63\.0 .* but @traxsharp\/state-machine 1\.64\.0 is installed\. Install @traxsharp\/state-machine@1\.63\.0, or regenerate the twin with trax 1\.64\.0/,
    );
  });

  it('does not hold a build from source to a version, on either side', async () => {
    const released = await engineAt('1.64.0');
    expect(() => released.requireEngineVersion('0.0.0')).not.toThrow();
    const fromSource = await engineAt(undefined);
    expect(() => fromSource.requireEngineVersion('1.63.0')).not.toThrow();
  });
});
